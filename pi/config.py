# ── Горка в КАРТЕ ────────────────────────────────────────────
# Не путать с assist_mode='ramp' выше: тот решает, каким током тянуть, а
# это - где робот окажется в карте. Горка обычно 25° (бывает до 30°), но
# на один островок могут вести горки разной длины, а значит и пологие -
# 2-3 плитки на высоту 25-градусной одноплиточной это 8-12°. Любой длины,
# на ней нет меток, цветных плиток и препятствий, после неё - только белая
# или чекпоинт. Поэтому на горке НЕ останавливаемся вовсе: проезжаем её
# одним куском, а число плиток считаем по энкодерам между подножием и
# гребнем.
#
# Чем горка отличается от всего остального - наклоном, который ДЕРЖИТСЯ
# на ходу. Лежачий полицейский (1-2см) и ступенька (≤2см) дают короткий
# всплеск в несколько градусов, препятствие (≥15см) не даёт проехать с
# задранным носом ни сантиметра. Кандидат в горку - >=RAMP_MAP_DEG на
# протяжении RAMP_CONFIRM_CM хода по одометрии (по ходу, а не по времени:
# стоящий на бордюре робот может быть задран сколько угодно долго).
# Порог низкий ради пологих горок, поэтому ступенька (одна ось выше другой
# на 2см - ~10° на всю базу) тоже проходит в кандидаты; окончательно горку
# от неё отличают длина (RAMP_MIN_LEN_CM) и высота (RAMP_MIN_RISE_CM),
# когда стало ровно.
