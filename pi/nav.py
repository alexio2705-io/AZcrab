def _link_reopen():
    """Ошибка порта на ходу (не закрытие на выходе): переоткрываем, пока не
    получится. False - порт закрыт нарочно, поток должен выйти."""
    if not _link.is_open:
        return False
    print("\n  [WARN] ошибка порта ESP - переподключаюсь")
    while True:
        time.sleep(0.5)
        try:
            _link.close()
            _link.open()
            return True
        except (serial.SerialException, OSError):
            pass


def _telem_thread():
    global _telem_seq, _telem_t, _bad_ver, _bad_crc, _seq_lost
    buf = bytearray()
    since = 0            # байт от предыдущего маркера 0xAA55 до текущего
    have_prev = False
    last_seq = None      # seq прошлого пакета - для счёта пропусков
    boot_id = None       # boot_id ESP - его смена значит ребут
    gyro_was = color_was = True   # чтобы сказать о пропаже свежести один раз
    while True:
        try:
            # 4096, а не 256: при TELEM_HZ=200 в 256 байт влезает всего
            # 6 пакетов, и если поток на мгновение не получил процессор
            # (YOLO, лидар - тот же GIL), разбор начинал отставать пачками.
            chunk = _link.read(max(1, min(_link.in_waiting, 4096)))
        except (serial.SerialException, OSError, TypeError):
            if _link is not None and _link_reopen():
                buf.clear()
                have_prev = False
                continue
            return          # порт закрыт на выходе из main()
        if not chunk:
            continue
        buf.extend(chunk)
        while len(buf) >= PKT_SIZE:
            if buf[0] != MAGIC[0] or buf[1] != MAGIC[1]:
                del buf[0]
                since += 1
                continue
            if have_prev and len(_magic_gaps) < 64:
                _magic_gaps[since] = _magic_gaps.get(since, 0) + 1
            have_prev = True
            since = 0
            body = bytes(buf[2:PKT_SIZE])
            # Версия - раньше CRC: она отсекает чужую раскладку сразу и
            # называет причину, а CRC только молча выбросит кадр. Маркер мог
            # быть случайным (внутри мусора) - тогда настоящий пакет лежит
            # внутри этих 51 байт, поэтому при любой ошибке съедаем 1 байт,
            # а не весь кадр. "Чужой версией" считаем кадр, за которым сразу
            # идёт следующий маркер: у случайного такого нет.
            if body[0] != TELEM_VER:
                if (len(buf) >= PKT_SIZE + 2 and buf[PKT_SIZE] == MAGIC[0]
                        and buf[PKT_SIZE + 1] == MAGIC[1]):
                    _bad_ver += 1
                del buf[0]
                since = 1
                continue
            if crc16(body[:-2]) != body[-2] | (body[-1] << 8):
                _bad_crc += 1
                del buf[0]
                since = 1
                continue
            since = PKT_SIZE          # столько сейчас будет съедено
            del buf[:PKT_SIZE]
            (_ver, seq, yaw, yaw_rate, pitch, roll, ax, ay, az, color,
             cr, cg, cb, cc, lcm, rcm, status, flags,
             z_cnt, esp_boot, cmd_err, _crc) = struct.unpack(FMT, body)
            # Пока только в лог: реакции на поле на эти флаги нет.
            if boot_id is not None and esp_boot != boot_id:
                print(f"\n  [WARN] ESP ПЕРЕЗАГРУЗИЛСЯ (boot_id {boot_id:04X} -> "
                      f"{esp_boot:04X}): одометрия и пауза на ESP сброшены")
                last_seq = None       # seq тоже начат заново - не пропуск
            boot_id = esp_boot
            if last_seq is not None:
                _seq_lost += (seq - last_seq - 1) & 0xFF
            last_seq = seq
            gyro_fresh, color_fresh = bool(flags & 32), bool(flags & 64)
            if gyro_fresh != gyro_was:
                print("\n  [WARN] гироскоп ESP замолчал - yaw замер"
                      if not gyro_fresh else "\n  гироскоп ESP снова идёт")
                gyro_was = gyro_fresh
            if color_fresh != color_was:
                print("\n  [WARN] датчик цвета ESP не читается - цвет старый"
                      if not color_fresh else "\n  датчик цвета ESP снова читается")
                color_was = color_fresh
            with _lock:
                _state["yaw"] = float(yaw)
                _state["yaw_rate"] = float(yaw_rate)
                _state["pitch"] = float(pitch)
                _state["roll"] = float(roll)
                # Модуль считаем здесь, чтобы у всех читателей он был один и
                # тот же; вертикаль хранится отдельно - именно она отличает
                # подъём от тряски (см. детектор подъёма).
                _state["accel"] = math.sqrt(ax * ax + ay * ay + az * az)
                _state["az"] = float(az)
                _state["rgbc"] = (cr, cg, cb, cc)
                _state["lcm"] = float(lcm)
                _state["rcm"] = float(rcm)
                _state["color"] = int(color)
                _state["clicker1"] = bool(flags & 1)
                _state["clicker2"] = bool(flags & 2)
                _state["enc_left_online"] = bool(flags & 4)
                _state["enc_right_online"] = bool(flags & 8)
                _state["btn1"] = bool(flags & 16)
                _state["esp_status"] = int(status)
                _state["z_cnt"] = int(z_cnt)
                _state["gyro_fresh"] = gyro_fresh
                _state["color_fresh"] = color_fresh
                _state["esp_cmd_err"] = int(cmd_err)
                _state["telem_ok"] = True
            # Вне _lock: у этих двух свой смысл (такт петли и здоровье
            # линка), и читаются они без блокировки, атомарно по GIL.
            _telem_t = time.monotonic()
            _telem_seq += 1
            _telem_evt.set()
            if status == 0:
                _esp_running.set()
            else:
                _esp_running.clear()


