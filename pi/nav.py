def _maze_cell(cx, cy):
    """Запись клетки в _maze, создаёт её (все 4 стороны неизвестны), если
    клетка встретилась впервые - в том числе для клетки, где робот ещё
    не стоял, но её сторону уже подтвердил сосед (см. _set_wall)."""
    return _maze.setdefault((cx, cy), [None, None, None, None])


def _next_cell(cx, cy, d):
    """Куда ведёт ребро (cx,cy)->d: обычно в соседа, а если это известная
    горка - в клетку на другом её конце (другой этаж, см. _ramps)."""
    r = _ramps.get((cx, cy, d))
    if r is not None:
        return r[0], r[1]
    return cx + _DX[d], cy + _DY[d]


def _walls_match(cell, hdg, walls_rel):
    """Свежий замер стоя (относительно курса hdg) не противоречит тому,
    что карта уже знает про cell. Зад не сравниваем - это ребро горки.
    Совпадением считаем хотя бы две известные стороны и ни одного
    расхождения."""
    known = _maze.get(cell)
    if known is None:
        return False
    rel_to_abs = {'front': hdg, 'right': (hdg + 1) % 4, 'left': (hdg + 3) % 4}
    n = 0
    for rel, d in rel_to_abs.items():
        if known[d] is None:
            continue
        if known[d] != walls_rel[rel]:
            return False
        n += 1
    return n >= 2


def record_ramp(cx, cy, d, info, measure=None):
    """drive_cells() проехал горку из (cx,cy) курсом d - заносит её в карту
    и возвращает клетку, где робот теперь стоит.

    Этаж - текущий ±1 (горка меняет этаж ровно на один), клетка - по пути
    в плане (RAMP_PLAN_WARN_FRAC): так две горки разной длины на один
    островок приводят в одни и те же клетки. Если этаж уже разведан, округление
    проекции проверяется замером стен (measure() -> как _measure_cell):
    из клеток на k-1, k, k+1 берётся посещённая, чьи стены совпали.

    Если эта горка уже известна (едем по ней второй раз или обратно) -
    берём записанный конец, а не новый замер: карта не должна расползаться
    от того, что энкодеры в этот раз насчитали иначе."""
    known = _ramps.get((cx, cy, d))
    if known is not None:
        if info is not None and info["tiles"] != known[2]:
            print(f"    [WARN] горка: сейчас ~{info['tiles']} плит., в карте "
                  f"{known[2]} - верю карте")
        return known[0], known[1]
    k, sign = info["cells"], info["sign"]
    z0 = level_of(cy)
    z = z0 + sign
    floor_known = any(level_of(v[1]) == z for v in _visited)
    y0 = cy - LEVEL_STRIDE * z0      # y внутри этажа

    def dest(kk):
        return cx + _DX[d] * kk, y0 + _DY[d] * kk + LEVEL_STRIDE * z

    bx, by = dest(k)
    cands = [kk for kk in (k, k - 1, k + 1) if kk >= 1]
    if floor_known and measure is not None and any(dest(kk) in _visited for kk in cands):
        walls = measure()
        pick = next((kk for kk in cands
                     if dest(kk) in _visited and _walls_match(dest(kk), d, walls)), None)
        if pick is None:
            if dest(k) in _visited:
                print(f"    [WARN] горка: этаж {z} знакомый, но стены в "
                      f"{dest(k)} не сходятся с замером - ставлю как посчитано")
        elif pick != k:
            print(f"    горка: по стенам поправил клетку на {pick - k:+d}")
            bx, by = dest(pick)
        else:
            print(f"    горка: знакомый этаж {z}, стены в {dest(k)} сошлись")

    # Замер стоя у подножия видел спереди "открыто" и завёл соседа - это
    # первая плитка горки, клеткой она не является. То же на другом конце,
    # если этот конец видели раньше с островка. Убираем, иначе BFS считал бы
    # их неразведанными и искал бы к ним путь вечно.
    for ph in ((cx + _DX[d], cy + _DY[d]), (bx - _DX[d], by - _DY[d])):
        if ph not in _visited:
            _maze.pop(ph, None)
    n = info["tiles"]
    _ramps[(cx, cy, d)] = (bx, by, n, sign)
    _ramps[(bx, by, _OPP[d])] = (cx, cy, n, -sign)
    open_edge(cx, cy, d)      # по _next_cell это уже ребро до (bx, by)
    print(f"  ⛰ ГОРКА {'вверх' if sign > 0 else 'вниз'}: ~{n} плит., "
          f"({cx},{cy}) → ({bx},{by}), этаж {z}"
          f"{' (знакомый)' if floor_known else ''}, высота {info['rise_cm']:+.0f}см")
    return bx, by


def level_of(cy):
    """Этаж клетки по её cy - см. LEVEL_STRIDE."""
    return watch_logic.level_of(cy, LEVEL_STRIDE)


def _set_wall(cx, cy, d, present):
    """Стена по абсолютному направлению d из (cx,cy) - одна и та же стена
    сразу выставляется у обеих клеток, которые она разделяет."""
    _maze_cell(cx, cy)[d] = present
    nx, ny = _next_cell(cx, cy, d)
    _maze_cell(nx, ny)[_OPP[d]] = present


def _edge_key(cx, cy, d):
    nx, ny = _next_cell(cx, cy, d)
    return frozenset(((cx, cy, d), (nx, ny, _OPP[d])))


def vote_wall(cx, cy, d, present):
    """Голос лидара за стену (present=True) или проход на ребре (cx,cy)->d.
    Итог - знак суммы голосов; при равенстве остаётся прежнее значение.
    Рёбра из _edge_fixed голосами не меняются. Смену уже известного
    значения печатает - по логу видно, где лидар ошибался."""
    key = _edge_key(cx, cy, d)
    if key in _edge_fixed:
        return
    v = _wall_votes.get(key, 0) + (1 if present else -1)
    v = max(-WALL_VOTE_CAP, min(WALL_VOTE_CAP, v))
    _wall_votes[key] = v
    old = _maze_cell(cx, cy)[d]
    new = True if v > 0 else False if v < 0 else (present if old is None else old)
    if old is not None and new != old:
        print(f"    ⟳ ({cx},{cy}) {_DIR_NAME[d]}: "
              f"{'стена' if old else 'проход'} → {'стена' if new else 'проход'} "
              f"(голоса {v:+d})")
    _set_wall(cx, cy, d, new)


def close_edge(cx, cy, d):
    """Ребро непроезжее по факту (упёрлись) - навсегда, голоса не в счёт."""
    _edge_fixed[_edge_key(cx, cy, d)] = True
    _set_wall(cx, cy, d, True)


def open_edge(cx, cy, d):
    """Ребро проезжее по факту (проехали) - голоса больше не в счёт. Если
    оно уже было закрыто по факту, это сильнее: туда упирались."""
    key = _edge_key(cx, cy, d)
    if _edge_fixed.get(key) is True:
        return
    _edge_fixed[key] = False
    _set_wall(cx, cy, d, False)


def set_cell_walls(cx, cy, hdg, walls_rel):
    """walls_rel: {'front','right','left','back': bool} - относительно
    текущего курса hdg. Переводит в абсолютные направления и голосует ими
    за стены карты (см. vote_wall)."""
    rel_to_abs = {'front': hdg, 'right': (hdg + 1) % 4,
                  'back': (hdg + 2) % 4, 'left': (hdg + 3) % 4}
    for rel, present in walls_rel.items():
        vote_wall(cx, cy, rel_to_abs[rel], present)


def block_direction(cx, cy, d):
    """Считать ребро (cx,cy)->d непроезжим, хотя лидар мог видеть его как
    открытое - для случаев, которые лидар не предсказывает (чёрная плитка,
    непреодолённое препятствие, бампер вплотную). BFS будет обходить его
    так же, как настоящую стену."""
    close_edge(cx, cy, d)
    _blocked.add(_next_cell(cx, cy, d))


def open_dirs(cx, cy):
    """Направления из (cx,cy), про которые точно известно, что там открыто
    И соседняя клетка не помечена непроезжей."""
    cell = _maze.get((cx, cy))
    if cell is None:
        return []
    return [d for d in range(4)
            if cell[d] is False and _next_cell(cx, cy, d) not in _blocked]


def find_path_bfs(start, goal_test, hdg=0):
    """Кратчайший (по числу клеток) путь от start по уже известным открытым
    рёбрам карты до ближайшей клетки, для которой goal_test() верно.

    Из равных по длине путей выигрывает тот, что раньше сворачивает в
    приоритетную сторону (_side_pref): соседи каждой клетки перебираются
    по SIDE_ORDER относительно курса, которым в неё въехали (для start -
    hdg, текущий курс робота).

    Возвращает список направлений (0..3, по одному на клетку пути; первый
    шаг - первый элемент) или None, если ни одна подходящая клетка не
    достижима по разведанной части лабиринта."""
    return runplan.bfs_path(start, hdg, open_dirs, _next_cell, goal_test,
                            SIDE_ORDER[_side_pref])


def find_frontier_path(cx, cy, hdg=0):
    """Путь до ближайшей ещё не посещённой клетки - см. find_path_bfs().
    None означает, что разведанная часть лабиринта исчерпана: из текущей
    клетки по известным открытым рёбрам больше некуда идти."""
    return find_path_bfs((cx, cy), lambda c: c not in _visited, hdg)


def _write_state(cx, cy, hdg, checkpoint, phase):
    """Снимок карты + найденных меток -> STATE_PATH, для map_web.py.

    Пишется во ВРЕМЕННЫЙ файл и переименовывается (os.replace) - атомарно
    с точки зрения читателя: map_web.py никогда не увидит наполовину
    записанный JSON, даже если откроет файл ровно в момент записи.
    Ошибки диска/прав не должны ронять заезд - лог и молча пропускаем.
    """
    try:
        data = {
            "ts": time.strftime("%H:%M:%S"),
            "phase": phase,
            "robot": {"cx": cx, "cy": cy, "hdg": hdg, "dir": _DIR_NAME[hdg]},
            "checkpoint": {"cx": checkpoint[0], "cy": checkpoint[1],
                           "hdg": checkpoint[2]},
            # "x,y" вместо кортежа - ключи JSON обязаны быть строками.
            "maze": {f"{x},{y}": walls for (x, y), walls in _maze.items()},
            "visited": [[x, y] for x, y in _visited],
            "blocked": [[x, y] for x, y in _blocked],
            "blue_done": [[x, y] for x, y in _blue_cells],
            "level_stride": LEVEL_STRIDE,
            "ramps": [[x, y, d, bx, by, n, sgn]
                      for (x, y, d), (bx, by, n, sgn) in _ramps.items() if sgn > 0],
            "victims": _victim_log,
        }
        tmp = STATE_PATH + ".tmp"
        with open(tmp, "w") as f:
            json.dump(data, f)
        os.replace(tmp, STATE_PATH)
    except OSError as e:
        print(f"  [WARN] не удалось записать {STATE_PATH}: {e}")


def wait_start_button():
    """Ждёт нажатия одной из двух кнопок старта (активный уровень LOW):
    GPIO27 - приоритет левой руки, GPIO25 - правой. Выставляет _side_pref.
    Аппаратный RC-фильтр (750R+0.1мкФ) на GPIO25 уже гасит дребезг, здесь
    только подтверждение вторым чтением и ожидание отпускания, чтобы одно
    нажатие не срабатывало дважды."""
    global _side_pref
    pins = {START_BTN_GPIO: "right", LEFT_BTN_GPIO: "left"}
    GPIO.setmode(GPIO.BCM)
    GPIO.setup(START_BTN_GPIO, GPIO.IN)
    GPIO.setup(LEFT_BTN_GPIO, GPIO.IN, pull_up_down=GPIO.PUD_UP)
    print(f"Нажмите GPIO{LEFT_BTN_GPIO} (левая рука) или "
          f"GPIO{START_BTN_GPIO} (правая рука) для старта...")
    pin = None
    while pin is None:
        for p in pins:
            if GPIO.input(p) == GPIO.LOW:
                time.sleep(0.02)
                if GPIO.input(p) == GPIO.LOW:
                    pin = p
                    break
        time.sleep(0.01)
    while GPIO.input(pin) == GPIO.LOW:
        time.sleep(0.01)
    _side_pref = pins[pin]
    print(f"  приоритет: {'ЛЕВАЯ' if _side_pref == 'left' else 'ПРАВАЯ'} рука "
          f"(GPIO{pin})")


def handle_lift(resume_hdg):
    """Робота сняли с поля. Ждём, пока его поставят ровно и нажмут кнопку,
    и восстанавливаем систему отсчёта. Сейчас не используется (сторож
    подъёма отключён) - перезапуск идёт по BTN_1, см. restart_from_checkpoint.

    resume_hdg - курс (0=N,1=E,2=S,3=W) ЧЕКПОИНТА, то есть направление, в
    котором робота надо поставить. Знать его обязательно: судья ставит робота
    как придётся, а вся карта (клетки, дедупликация жертв в VictimDetector)
    живёт в системе, заданной YAW_ORIGIN. Поэтому YAW_ORIGIN пересчитывается
    ОТ ФАКТИЧЕСКОГО курса так, чтобы текущее направление означало именно
    resume_hdg - заодно это поглощает неточность установки рукой, ведь
    snap_target() всё равно округляет к сетке 90°.
    """
    global YAW_ORIGIN
    print("\n  ✋ РОБОТА СНЯЛИ С ПОЛЯ - моторы выключены")
    stop()
    leds_lifted(True)
    print(f"  Поставьте робота на чекпоинт курсом {_DIR_NAME[resume_hdg]} "
          f"и нажмите GPIO{LEFT_BTN_GPIO} (левая) или GPIO{START_BTN_GPIO} (правая)")

    # Сначала - ровно и неподвижно: кнопку, нажатую пока робот ещё в руках,
    # принимать нельзя, иначе YAW_ORIGIN зафиксируется по курсу в воздухе.
    # Лента всё это время горит красным и гаснет ровно в тот момент, когда
    # датчик цвета снова видит плитку - то есть когда робота поставили, а не
    # когда нажали кнопку.
    steady = 0.0
    on_floor = False
    last = time.monotonic()
    while True:
        time.sleep(LIFT_POLL_S)
        now = time.monotonic()
        dt, last = now - last, now

        r, g, b, c = get_rgbc()
        floor_now = c >= TILE_MIN_C and (r - b) / c <= LIFT_AIR_RB
        if floor_now != on_floor:
            on_floor = floor_now
            leds_lifted(not on_floor)
            if on_floor:
                print("  Робот на полу - лента погашена")
        # На полу |a| не превышает 0.06, а сразу после установки, пока
        # человек ещё рядом, доходит до 0.25 - LIFT_STEADY_MS2 между ними.
        level = (telem_fresh()
                 and abs(get_roll()) < LIFT_SETTLE_ROLL_DEG
                 and abs(get_yaw_rate()) < LIFT_SETTLE_RATE_DPS
                 and get_accel() < LIFT_STEADY_MS2)
        steady = steady + dt if level else 0.0
        if steady >= LIFT_SETTLE_S:
            break
    print("  Робот стоит ровно - жду кнопку")
    wait_start_button()

    YAW_ORIGIN = (get_yaw() - 90.0 * resume_hdg + 360.0) % 360.0
    zero_odo()
    time.sleep(0.1)
    # _c_white НЕ пересчитываем: под роботом чекпоинт (зеркальный), а не
    # стартовая белая клетка - калибровка по нему испортила бы порог чёрной.
    _lifted.clear()
    leds_lifted(False)
    print(f"  ▶ Продолжаем, YAW_ORIGIN={YAW_ORIGIN:.1f}° "
          f"(текущий yaw={get_yaw():.1f}° = {_DIR_NAME[resume_hdg]})")


# После нажатия GPIO25 рука ещё может касаться робота - подождать, прежде
# чем мерить стены и курс.
RESTART_SETTLE_S = 0.5
# Отклонение от ближайшей стороны сетки больше этого - робот поставлен
# заметно криво, печатаем (курс всё равно выберется, см. detect_heading).
RESTART_SKEW_WARN_DEG = 25.0


def detect_heading(cx, cy):
    """Какой стороной робот стоит в клетке (cx,cy) - 0=N..3=W.

    Гироскоп: BNO085 продолжает считать курс, пока робота несут в руках,
    поэтому угол от YAW_ORIGIN сразу даёт ближайшую из четырёх сторон.
    Лидар: свежий замер стен сверяется с картой этой клетки при каждом из
    четырёх поворотов. Рёбра, закрытые не стеной, а по факту (чёрная
    плитка, бампер - _blocked), не сравниваются: лидар видит там открыто.

    Решение: сторона по гироскопу, если стены с ней не спорят (или ни одна
    сторона не подходит - тогда лидару верить не по чему). Если спорят, а
    другая сторона подходит - берём её, ближайшую к гироскопу: стена по
    лидару медианой из трёх сканов ошибается реже, чем гироскоп на 45°+.

    Возвращает (курс, совпал_ли_с_гироскопом)."""
    off = angle_err(get_yaw(), YAW_ORIGIN)
    k = int(round(off / 90.0))
    h_gyro = k % 4
    skew = off - 90.0 * k

    wait_scan(2)
    wr = _walls_rel_map(measure_walls(WALL_VOTE_SCANS, fresh=True))
    rel = [wr["front"], wr["right"], wr["back"], wr["left"]]
    known = _maze.get((cx, cy))

    def mismatches(h):
        bad = n = 0
        for i in range(4):
            d = (h + i) % 4
            if known is None or known[d] is None or _next_cell(cx, cy, d) in _blocked:
                continue
            n += 1
            bad += known[d] != rel[i]
        return bad, n

    score = {h: mismatches(h) for h in range(4)}
    fits = [h for h in range(4) if score[h][0] == 0 and score[h][1] > 0]
    circ = lambda h: min((h - h_gyro) % 4, (h_gyro - h) % 4)

    seen = "".join("FRBL"[i] if rel[i] else "." for i in range(4))
    print(f"  курс по гироскопу: {_DIR_NAME[h_gyro]} (перекос {skew:+.0f}°), "
          f"стены F R B L: {seen}, подходят: "
          f"{','.join(_DIR_NAME[h] for h in fits) or 'ни одна'}")
    if abs(skew) > RESTART_SKEW_WARN_DEG:
        print("  [WARN] робот стоит заметно криво относительно сетки")

    if h_gyro in fits or not fits:
        if not fits:
            print("  [WARN] стены не сходятся с картой ни при одном курсе - "
                  "верю гироскопу")
        return h_gyro, True
    h = min(fits, key=circ)
    print(f"  [WARN] по стенам {_DIR_NAME[h]}, а гироскоп говорил "
          f"{_DIR_NAME[h_gyro]} - верю стенам")
    return h, False


def restart_from_checkpoint(checkpoint):
    """BTN_1 (GPIO47) на ESP: lack of progress, робота переносят на последний
    чекпоинт. ESP уже заглушил моторы сам; здесь только ждём GPIO25 на
    малине - никаких автоматических проверок "поставили ли ровно" (как в
    handle_lift): они срабатывали плохо, кнопку жмёт человек, когда робот
    стоит. Карта сохраняется целиком.

    Ставить можно любой стороной - сторону определяет detect_heading()
    (гироскоп до ближайших 90° плюс сверка стен с картой). А сетку поля
    после этого ВСЕГДА строим заново от того, как робот стоит сейчас:
    ставят его ровно, а гироскоп за время в руках уплывает на 5-10°, и с
    его сеткой робот потом ехал бы криво."""
    global YAW_ORIGIN
    cx, cy, _ = checkpoint
    stop()
    print(f"\n  ✋ ПЕРЕЗАПУСК С ЧЕКПОИНТА - моторы выключены.\n"
          f"  Поставьте робота на чекпоинт ({cx},{cy}, этаж {level_of(cy)}) "
          f"любой стороной и нажмите GPIO{LEFT_BTN_GPIO} (левая рука) "
          f"или GPIO{START_BTN_GPIO} (правая рука)")
    leds_sleep(True)
    wait_start_button()
    leds_sleep(False)
