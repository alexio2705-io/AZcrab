def wait_scan(n=2, timeout=3.0):
    """False - свежих сканов нет (лидар молчит): get_walls*() отдаст старое."""
    start = _scan_cnt
    t0 = time.time()
    while _scan_cnt - start < n:
        if time.time() - t0 > timeout:
            print(f"\n  [WARN] лидар молчит {timeout:.0f}с - стены могут быть устаревшими")
            return False
        time.sleep(0.04)
    return True


# Последний замер стоя - для повторного использования, пока робот не сдвинулся.
# На новой клетке стены мерились дважды подряд с места: align_at_wall() (он
# решает, что доводка не нужна) и тут же _measure_cell() - ещё ~0.3с на тот же
# самый вид. После поворота - то же с scan_sides(). Замер годен, пока робот
# не сдвинулся и не повернулся (одометрия, курс) и пока он свежий.
WALLS_REUSE_S = 1.5
WALLS_REUSE_CM = 0.3
WALLS_REUSE_DEG = 1.5
_walls_cache = None      # (monotonic, n, (l_cm, r_cm), yaw, walls)


def _walls_cached(n):
    if _walls_cache is None:
        return None
    t, cn, (l0, r0), yaw0, w = _walls_cache
    l, r = get_odo()
    if (cn >= n and time.monotonic() - t <= WALLS_REUSE_S
            and abs(l - l0) <= WALLS_REUSE_CM and abs(r - r0) <= WALLS_REUSE_CM
            and abs(angle_err(get_yaw(), yaw0)) <= WALLS_REUSE_DEG):
        return dict(w)
    return None


@_timed("лидар")
def measure_walls(n=WALL_VOTE_SCANS, fresh=False):
    """Медиана n сканов - одиночный промах лидара не решает за нас.

    Берёт замер СИММЕТРИЧНЫМ боковым окном (get_walls_still): все вызовы
    этой функции происходят, когда робот уже стоит в центре клетки, а там
    асимметричное окно SIDE_BACK_LIMIT только отнимает точки - см.
    SIDE_BACK_LIMIT_STILL в walls.py.

    Если робот с прошлого замера не двигался - возвращает его же (см.
    _walls_cache); fresh=True - всегда новый замер.
    """
    global _walls_cache
    if not fresh:
        w = _walls_cached(n)
        if w is not None:
            return w
    FAR = 9999.0
    odo0, yaw0 = get_odo(), get_yaw()
    samples = {"front": [], "right": [], "left": [], "back": []}
    fresh_ok = True
    for _ in range(max(1, n)):
        fresh_ok &= wait_scan(1)
        w = get_walls_still()
        for k in samples:
            samples[k].append(w[k] if w[k] is not None else FAR)
    out = {}
    for k, lst in samples.items():
        m = sorted(lst)[len(lst) // 2]
        out[k] = None if m >= FAR else m
    # Положение - на НАЧАЛО замера: если робот сдвинулся во время него, то
    # следующая проверка это увидит и замер не переиспользует.
    if fresh_ok:     # устаревший замер не кладём в кеш
        _walls_cache = (time.monotonic(), max(1, n), odo0, yaw0, dict(out))
    return out


def measure_front_confirmed(n=WALL_VOTE_SCANS, retries=3):
    """Как measure_walls(), но если перед вышел пустым - переспрашивает ещё
    несколько раз перед тем, как поверить, что там правда открыто.

    Нужно из-за YOLO: скан жертвы грузит CPU на сотни мс - секунду, фоновый
    поток лидара (чистый Python, тот же GIL) на это время отстаёт, и первые
    замеры после скана могут приходить пустыми оборотами. Ложное "стена
    есть" за переспрашивание ничего не стоит (лишний поворот), а ложное
    "открыто" ведёт прямо в стену - разная цена ошибки оправдывает разную
    осторожность.
    """
    w = measure_walls(n)
    for _ in range(retries):
        if w["front"] is not None:
            break
        wait_scan(2)
        w = measure_walls(n, fresh=True)   # переспрос - это всегда новый замер
    return w


# ══════════════════════════════════════════════════════════════
#  Поворот по гироскопу
# ══════════════════════════════════════════════════════════════
def snap_target(delta_deg=0.0):
    """Текущий курс, подтянутый к сетке 90° от YAW_ORIGIN, плюс delta_deg."""
    rel_now = (get_yaw() - YAW_ORIGIN + 360) % 360
    snap_rel = round(rel_now / 90) * 90 % 360
    return (YAW_ORIGIN + snap_rel + delta_deg + 360) % 360


def turn(delta_deg):
    """Поворот на delta_deg от снэпнутого к сетке 90° текущего курса.
    False - не доехал (см. turn_to)."""
    return turn_to(snap_target(delta_deg), label=f"{delta_deg:+.0f}°")


def gyro_heading():
    """Ближайшая к гироскопу сторона сетки поля, 0=N..3=W - как в
    detect_heading(), только без сверки со стенами."""
    return int(round(angle_err(get_yaw(), YAW_ORIGIN) / 90.0)) % 4


@_timed("поворот")
def turn_to(target, label=None):
    """Поворот на АБСОЛЮТНЫЙ курс target (град), без привязки к сетке 90°.

    Нужен отдельно от turn(): у объезда препятствия (bumper_side) курс после
    поворота на 45° лежит МЕЖДУ узлами сетки, и turn(delta) на возврат снова
    вызвал бы snap_target() - а тот привязывается к БЛИЖАЙШЕМУ узлу сетки от
    ТЕКУЩЕГО (уже 45°-смещённого) курса, что неоднозначно и может увести не
    туда. turn_to() возвращает точно на тот курс, что был до манёвра.

    Возвращает True, если доехал до цели; False - прервали (пауза, пропала
    телеметрия) или вышел TURN_TIMEOUT_S. Тогда курс в карте "как просили"
    считать нельзя - вызывающий берёт его с гироскопа (gyro_heading()).
    """
    global _turn_ff
    settled = 0
    tag = label if label is not None else f"{target:.1f}°"

    print(f"    поворот {tag}  цель={target:.1f}°  yaw={get_yaw():.1f}°")

    # Разгон по времени (smoothstep): пик ускорения = 1.5 * полка / время.
    t_up = 1.5 * TURN_RATE_MAX_DPS / TURN_ACCEL_DPS2
    # Команды колёсам за последние ~100мс - чтобы сравнивать достигнутую
    # скорость с командой, поданной на запаздывание петли раньше, а не с
    # текущей (на разгоне/торможении они заметно расходятся).
    hist = deque()

    t0 = time.monotonic()
    deadline = t0 + TURN_TIMEOUT_S
    t_ramp = t0            # начало разгона; после манёвра выхода - заново
    stuck_since = None
    stuck_stage = 0        # сколько ступеней выхода из застревания уже было
    boost = False
    telem_seq = _telem_seq
    while time.monotonic() < deadline:
        if interrupted():
            # Пауза ESP глушит моторы сама. Иначе (пропала телеметрия)
            # последняя команда вращения работала бы до failsafe ESP.
            if not get_esp_paused() and not _lifted.is_set():
                brake()
            return False
        now = time.monotonic()
        elapsed = now - t_ramp
        rate = get_yaw_rate()
        # Остаток угла В СТОРОНУ ЦЕЛИ (>0 - крутиться по часовой), и он же с
        # поправкой на запаздывание: к моменту исполнения команды робот уже
        # довернётся на rate * TURN_LEAD_S.
        rem = -angle_err(get_yaw(), target)
        rem_eff = rem - rate * TURN_LEAD_S

        tilted = is_tilted()
        tol = TURN_TILT_TOL_DEG if tilted else TURN_TOL_DEG
        done_rate = TURN_TILT_DONE_RATE_DPS if tilted else TURN_DONE_RATE_DPS
        if abs(rem) <= tol and abs(rate) <= done_rate:
            settled += 1
            if settled >= TURN_SETTLE:
                break
        else:
            settled = 0

        # ── Выход из застревания ─────────────────────────────
        # Манёвр (откат/возврат) блокирующий: на его время сдвигаем дедлайн и
        # начинаем разгон заново, иначе профиль сразу дал бы полку скорости.
        maneuver = None
        if boost and (abs(rate) > TURN_DONE_RATE_DPS
                      or abs(rem) <= TURN_STUCK_MIN_DEG):
            boost = False   # закрутился или подошёл к цели - дальше профиль
        if abs(rem) > TURN_STUCK_MIN_DEG and abs(rate) < TURN_STUCK_RATE_DPS \
                and elapsed > t_up:
            if stuck_since is None:
                stuck_since = now
            elif now - stuck_since >= TURN_STUCK_S and stuck_stage < 3:
                stuck_stage += 1
                stuck_since = None
                if stuck_stage == 1:
                    boost = True
                    print(f"    застрял на повороте (осталось {rem:+.1f}°): дожимаю")
                elif stuck_stage == 2:
                    maneuver = ("застрял", -TURN_STUCK_BACK_MM)
                else:
                    maneuver = ("застрял", +TURN_STUCK_BACK_MM)
        else:
            stuck_since = None
        if maneuver is not None:
            why, mm = maneuver
            print(f"    {why} на повороте (осталось {rem:+.1f}°): "
                  f"{'назад' if mm < 0 else 'вперёд'} {abs(mm):.0f}мм")
            brake()
            t_m = time.monotonic()
            creep_mm(mm, get_yaw())
            dt_m = time.monotonic() - t_m
            deadline += dt_m
            t_ramp = time.monotonic()
            stuck_since = None
            settled = 0
            hist.clear()
            telem_seq = _telem_seq
            continue

        # ── Профиль угловой скорости ──────────────────────────
        ss = min(1.0, elapsed / t_up)
        ss = ss * ss * (3.0 - 2.0 * ss)
        w_ref = min(TURN_RATE_MAX_DPS * ss,
                    math.sqrt(2.0 * TURN_DECEL_DPS2 * abs(rem_eff)))
        w_ref = math.copysign(w_ref, rem_eff)

        # ── Колёса: прямая подача + поправка по скорости ─────
        spd = w_ref * _turn_ff + (w_ref - rate) * TURN_RATE_KP
        spd = max(-TURN_MAX_CMS, min(TURN_MAX_CMS, spd))
        # Страховка от залипания: профиль у самой цели просит почти ноль, и
        # если трение успело остановить робота раньше - дожимаем минимумом.
        if (abs(rem) > tol and abs(spd) < TURN_MIN_CMS
                and abs(rate) < done_rate):
            spd = math.copysign(TURN_MIN_CMS, rem)
        # Ступень 1: пока корпус стоит - не меньше TURN_STUCK_BOOST_CMS. Как
        # только закрутился, профиль снова ведёт сам (иначе перелёт у цели).
        if (boost and abs(rem) > TURN_STUCK_MIN_DEG
                and abs(rate) < TURN_DONE_RATE_DPS
                and abs(spd) < TURN_STUCK_BOOST_CMS):
            spd = math.copysign(TURN_STUCK_BOOST_CMS, rem)
        motors(spd * TURN_SIGN, -spd * TURN_SIGN)

        # ── Подстройка подачи ────────────────────────────────
        # Берём команду ~TURN_LEAD_S назад и сегодняшнюю скорость; только на
        # уверенном вращении (медленное - это трение покоя и шум) и в ту же
        # сторону, что команда.
        hist.append((now, spd))
        while len(hist) > 1 and now - hist[1][0] >= TURN_LEAD_S:
            hist.popleft()
        spd_then = hist[0][1]
        if (not tilted and abs(rate) > 60.0 and abs(spd_then) > TURN_MIN_CMS * 2
                and (rate > 0) == (spd_then > 0)):
            k = abs(spd_then) / abs(rate)
            k = max(TURN_FF_MIN, min(TURN_FF_MAX, k))
            _turn_ff += (k - _turn_ff) * TURN_FF_ADAPT

        # TURN_DT (15мс) был длиннее периода телеметрии и накладывал на
        # контур поворота собственное запаздывание; теперь шаг задаёт пакет.
        telem_seq = wait_telem(telem_seq, TURN_DT)

    settle_brake(0.10)
    done = settled >= TURN_SETTLE
    print(f"    итог yaw={get_yaw():.1f}°  ошибка={angle_err(get_yaw(), target):+.1f}°  "
          f"за {time.monotonic() - t0:.2f}с  TURN_FF={_turn_ff:.3f}"
          + (f"  застреваний={stuck_stage}" if stuck_stage else "")
          + ("" if done else "  НЕ ДОВЕРНУЛ (таймаут)"))
    return done


# ══════════════════════════════════════════════════════════════
#  Непрерывный проезд: клетки подряд, без остановки между ними
# ══════════════════════════════════════════════════════════════
def _ramp_measure(log, sign):
    """Длина горки по записи (одометрия_см, pitch) за проезд.

    Подножие и гребень - по пересечению ПОЛОВИНЫ установившегося наклона:
    у подножия нос проходит половину уклона, когда центр робота примерно
    над изломом (передние колёса уже на горке, задние ещё на полу), у
    гребня - так же, и смещения на полбазы с обеих сторон взаимно гасятся.
    Порог по половине реального уклона, а не константой, чтобы горки 25° и
    30° мерились одинаково.

    Возвращает dict: sign, tiles, len_cm, slope, foot_cm, crest_cm,
    start_known (False - поехали уже с горки, длина занижена)."""
    ps = [p * sign for _, p in log]
    ds = [d for d, _ in log]
    on = sorted(p for p in ps if p >= RAMP_MAP_DEG)
    slope = on[len(on) // 2] if on else RAMP_MAP_DEG
    half = slope * 0.5
    # Участки выше половины уклона. У порога наклон дрожит (вибрация,
    # стыки плиток), и один участок рвётся на куски - склеиваем разрывы
    # короче RAMP_GAP_CM и берём самый длинный: это и есть горка.
    runs = []
    for i, p in enumerate(ps):
        if p < half:
            continue
        if runs and (runs[-1][1] == i - 1 or ds[i] - ds[runs[-1][1]] < RAMP_GAP_CM):
            runs[-1][1] = i
        else:
            runs.append([i, i])
    i_start, i_end = max(runs, key=lambda r: ds[r[1]] - ds[r[0]])
    len_cm = ds[i_end] - ds[i_start]
    cell_cm = CELL_MM / 10.0
    tiles = max(1, int(round(len_cm / cell_cm)))   # только для лога
    # Высота - по всему наклонному участку, включая заезд и съезд (там,
    # где pitch выше RAMP_FLAT_DEG), а не по всему проезду: смещение нуля
    # pitch на ровном накопило бы ошибку.
    j0, j1 = i_start, i_end
    while j0 > 0 and ps[j0 - 1] >= RAMP_FLAT_DEG:
        j0 -= 1
    while j1 < len(ps) - 1 and ps[j1 + 1] >= RAMP_FLAT_DEG:
        j1 += 1
    rise_cm = sign * sum((ds[i] - ds[i - 1]) * math.sin(math.radians(ps[i]))
                         for i in range(j0 + 1, j1 + 1))
    # Путь в плане от старта проезда (центр клетки у подножия) до гребня.
    plan_crest_cm = ds[0] + sum((ds[i] - ds[i - 1]) * math.cos(math.radians(ps[i]))
                                for i in range(1, i_end + 1))
    plan_cells = (plan_crest_cm + cell_cm * 0.5) / cell_cm
    k = max(1, int(round(plan_cells)))
    print(f"\n    горка: {len_cm*10:.0f}мм по уклону (~{len_cm/cell_cm:.2f} плит.), "
          f"уклон {slope:.1f}°, высота {rise_cm*10:+.0f}мм, "
          f"островок через {plan_cells:.2f} кл. в плане -> {k}")
    if abs(plan_cells - k) > RAMP_PLAN_WARN_FRAC:
        print("    [WARN] горка: островок в плане сдвинут почти на полклетки - "
              "с другой горки клетки могут не сойтись")
    if i_start == 0:
        print("    [WARN] горка: подножие не видно (поехали уже с наклона) - "
              "длина замерена не вся")
    return {"sign": sign, "tiles": tiles, "cells": k, "plan_cells": plan_cells,
            "rise_cm": rise_cm, "len_cm": len_cm, "slope": slope,
            "foot_cm": ds[i_start], "crest_cm": ds[i_end],
            "start_known": i_start > 0}


