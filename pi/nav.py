def leds_lifted(on):
    """Красный на ленте, пока робота держат на руках.

    Безопасна во всех положениях: лента опциональна (её может не быть -
    тогда _leds is None), а во время подъёма параллельно может доигрывать
    мигание жертвы, которое тоже пишет в ленту. Поэтому вызывается
    повторно из цикла ожидания в handle_lift() - последний писавший и
    выигрывает, а цикл пишет чаще.
    """
    if _leds is None:
        return
    try:
        if on:
            _leds.fill(*RED)
        else:
            _leds.clear()
        _leds.show()
    except Exception:
        pass


def leds_sleep(on):
    """Синий на ленте, пока робот спит по BTN_1 - см. restart_from_checkpoint."""
    if _leds is None:
        return
    try:
        if on:
            _leds.fill(*SLEEP)
        else:
            _leds.clear()
        _leds.show()
    except Exception:
        pass


def _lift_thread():
    """Сторожевой поток: вертикальное ускорение, потом датчик цвета.

    Отдельный поток, а не проверка в петле: во время YOLO-скана жертвы
    основные петли стоят до секунды, и подъём в этот момент иначе не
    заметили бы вовсе. Поток только выставляет флаг и глушит моторы -
    всё остальное делает handle_lift() из основного потока.

    Два шага, и ничего сверх них - см. комментарии над LIFT_* о том, какие
    признаки пробовались до этого и почему каждый из них пришлось убрать.
    """
    hist = []            # (время, az) за LIFT_AZ_WINDOW_S
    armed_at = None      # когда возникло подозрение
    air_since = None     # с какого момента датчик непрерывно видит не плитку
    while True:
        time.sleep(LIFT_POLL_S)
        # Пока подъём разбирает основной поток, детектору делать нечего.
        if _lifted.is_set() or not telem_fresh():
            hist.clear()
            armed_at = air_since = None
            continue

        now = time.monotonic()
        hist.append((now, get_az()))
        while hist and now - hist[0][0] > LIFT_AZ_WINDOW_S:
            hist.pop(0)

        # ── Шаг 1: длительное вертикальное ускорение ──────────
        if armed_at is None:
            az_mean = sum(z for _, z in hist) / len(hist)
            if abs(az_mean) > LIFT_AZ_MS2:
                armed_at = now
                air_since = None
                print(f"\n  [подъём?] вертикаль {az_mean:+.2f} м/с² за "
                      f"{LIFT_AZ_WINDOW_S:.1f}с - смотрю под робота")
            continue

        if now - armed_at > LIFT_ARM_TIMEOUT_S:
            armed_at = air_since = None
            continue

        # ── Шаг 2: что под роботом ────────────────────────────
        r, g, b, c = get_rgbc()
        rb = (r - b) / c if c >= TILE_MIN_C else -1.0
        if rb <= LIFT_AIR_RB:
            if air_since is not None:
                print(f"  [подъём?] отбой: под роботом плитка, "
                      f"(r-b)/c={rb:+.3f} (порог {LIFT_AIR_RB:.2f})")
            air_since = None
            continue

        if air_since is None:
            air_since = now
            continue
        if now - air_since < LIFT_AIR_CONFIRM_S:
            continue

        print(f"  [подъём?] под роботом не плитка: (r-b)/c={rb:+.3f} "
              f"держится {LIFT_AIR_CONFIRM_S:.1f}с")
        _lifted.set()
        leds_lifted(True)
        # Именно stop(), а не brake(): держать 0 dps в руках - это драка с
        # человеком и четыре греющихся мотора. Короткий brake перед этим
        # гасит инерцию, если робота подняли прямо на ходу.
        try:
            brake()
            time.sleep(0.05)
            stop()
        except Exception:
            pass


def interrupted():
    """Причина немедленно бросить текущий манёвр: пауза кнопкой на ESP,
    подъём робота с поля или пропавшая телеметрия."""
    return get_esp_paused() or _lifted.is_set() or not telem_fresh()


def _cmd(s):
    # Без flush(): это tcdrain, и на Pi он стоил 8.0мс на КАЖДУЮ команду
    # (замер: p50 7.97, max 8.02) против 0.03мс у самого write() - больше
    # такта петли (5мс). Ядро отправляет байты и так, 16 байт на 921600 -
    # это ~0.2мс. Дожимается только при выходе, перед закрытием порта.
    b = s.encode()
    with _write_lock:
        _link.write(b + b"*%04X\n" % crc16(b))    # CRC - см. robot_link.h


# Каждая команда хода превращается на ESP в ЧЕТЫРЕ кадра CAN. Управляющая
# петля теперь тактируется телеметрией (200 Гц), и без ограничителя поток
# кадров к моторам удвоился бы просто потому, что петля стала чаще считать -
# а шина CAN как раз то место, где это уже один раз вышло боком (см.
# ENC_POLL_HZ в motor.c). Свежие данные регулятору нужны, а подавать мотору
# новую уставку чаще, чем он её отрабатывает, - нет: закрытый контур скорости
# на LK живёт своим темпом. 100 Гц - ровно столько, сколько уходило на шину
# до перехода на такт по пакету.
MOTOR_CMD_HZ = 100
_last_drive_cmd_t = 0.0


def _drive_cmd(s):
    """Команда хода (M:/T:) с ограничением частоты - см. MOTOR_CMD_HZ.

    Пропуск безвреден: следующий тик пошлёт более свежее значение той же
    уставки. Через этот ограничитель НЕ идут ни тормоз, ни остановка, ни
    обнуление одометрии - они обязаны уходить немедленно и всегда.
    """
    global _last_drive_cmd_t
    now = time.monotonic()
    if now - _last_drive_cmd_t < 1.0 / MOTOR_CMD_HZ:
        return
    _last_drive_cmd_t = now
    _cmd(s)


def _drive_cmd_now(s):
    """То же, но мимо ограничителя, и с перевзводом его таймера: после
    тормоза/остановки следующая команда хода не должна ждать окна."""
    global _last_drive_cmd_t
    _last_drive_cmd_t = 0.0
    _cmd(s)


def motors(l, r): _drive_cmd(f"M:{l:.1f},{r:.1f}")
def torque(l, r, cap_cms=OBSTACLE_CAP_CMS):
    """Момент с потолком скорости колеса - см. OBSTACLE_CAP_CMS."""
    _drive_cmd(f"T:{l:.2f},{r:.2f},{cap_cms:.1f}")
def stop():       _drive_cmd_now("M:0.0,0.0")
def zero_odo():   _drive_cmd_now("Z")


def brake():      _drive_cmd_now("B")


def tilt_deg():
    """Наибольший перекос корпуса относительно ровного пола, градусы."""
    return max(abs(get_pitch() - _pitch_level), abs(get_roll()))


def is_tilted():
    """Стоим перекошенно - на препятствии, а не на полу."""
    return (abs(get_pitch() - _pitch_level) >= TILT_PITCH_DEG
            or abs(get_roll()) >= TILT_ROLL_DEG)


def settle_brake(pause_s=0.10):
    """Тормоз после манёвра. На ровном полу - как раньше: "B", и ESP держит
    0 dps ещё BRAKE_HOLD_US. На препятствии это удержание трясёт робота на
    люфте редукторов (см. TILT_*), поэтому там тормоз только до остановки,
    а потом моторы отпускаются - на небольшом перекосе робот и так стоит."""
    brake()
    time.sleep(pause_s)
    if is_tilted() and tilt_deg() < TILT_RELEASE_MAX_DEG:
        time.sleep(max(0.0, TILT_BRAKE_S - pause_s))
        stop()
        print(f"    на препятствии (перекос {tilt_deg():.0f}°) - удержание колёс снято")


def hold_while(fn, *args, period=1.0, **kwargs):
    """Держит активный тормоз фоновым потоком, пока выполняется fn(*args).

    Протокол сам отпускает 'B' через BRAKE_HOLD_US=3с на ESP (см.
    robot_link.h) - это рассчитано на короткие паузы между сериями команд,
    а не на растянутые действия вроде 5+с мигания лентой при находке жертвы.
    Без переподтверждения робота на последних секундах такого мигания ничто
    не держит - на наклонном полу или от толчка его может увести с центра
    клетки, а именно там начинается 5-секундный отсчёт по правилам.
    """
    stop_evt = threading.Event()

    def _keepalive():
        while not stop_evt.wait(period):
            try:
                brake()
            except (serial.SerialException, OSError) as e:
                print(f"  [WARN] keepalive тормоза: {e}")

    brake()
    t = threading.Thread(target=_keepalive, daemon=True)
    t.start()
    try:
        return fn(*args, **kwargs)
    finally:
        stop_evt.set()
        t.join(timeout=0.5)


# Ход сервы дозатора занимает ~1с (servo.h) - столько ждём после команды,
# прежде чем слать следующую или продолжать движение, иначе следующая же
# команда 'M:' встанет в очередь на ESP за ещё не отработавшим 'K:'.
DISPENSE_MOVE_S = 1.4   # K: на ESP блокирует cmd_task ~1.32с


def dispense(side):
    """side: 'L' или 'R' - высыпает один спасательный комплект из заднего
    бокового отсека (см. servo.h/robot_link.h, команда 'K:<side>')."""
    _cmd(f"K:{side}")
    time.sleep(DISPENSE_MOVE_S)


# Сколько комплектов выдано из каждого столбика за этот запуск (столбики
# заряжаются полными перед каждым заездом, поэтому счёт с нуля).
_kits_used = {"L": 0, "R": 0}
# Сколько комплектов влезает в столбик - всего на робота 8. Когда столбик
# пуст, серва им больше не машет: раньше робот после восьмого комплекта
# продолжал разворачиваться к жертвам и "выдавать" из пустых отсеков.
KITS_PER_COLUMN = 4


def kits_left():
    return sum(KITS_PER_COLUMN - n for n in _kits_used.values())


def dispense_kit():
    """Один комплект из того столбика, где их осталось больше, при
    равенстве - из левого. Так столбики чередуются и расходуются поровну.
    Раньше один комплект всегда шёл из левого, а два - из обоих, и левый
    пустел быстрее на каждую жертву с одним комплектом. Пустые столбики
    не трогаются; вызывающий проверяет kits_left() заранее."""
    side = "L" if _kits_used["L"] <= _kits_used["R"] else "R"
    if _kits_used[side] >= KITS_PER_COLUMN:
        side = "R" if side == "L" else "L"
    if _kits_used[side] >= KITS_PER_COLUMN:
        print("    комплекты кончились - выдавать нечего")
        return
    dispense(side)
    _kits_used[side] += 1
    print(f"    комплект из {'левого' if side == 'L' else 'правого'} столбика "
          f"(выдано: L={_kits_used['L']} R={_kits_used['R']})")


def angle_err(cur, tgt):
    e = cur - tgt
    while e > 180: e -= 360
    while e < -180: e += 360
    return e


def wall_present(d, thresh):
    return d is not None and d < thresh


