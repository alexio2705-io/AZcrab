def _drive_cells(max_cells, expect_ramp, cell, hdg):
    """Едет вперёд, пересекая границы клеток БЕЗ остановки, пока очередная
    клетка не потребует поворота (справа открылось или спереди стена), пока
    не кончится лимит клеток, или пока не вмешается бампер/авария/пауза.

    expect_ramp - по карте это ребро - горка (см. _ramps). Тогда подъём не
    отбраковывается как "лестница" по длине/высоте: невезучий замер на
    повторном проезде не должен остановить робота посреди известной горки.

    Возвращает (пройдено_клеток, причина):
      'stop'           - встали, вызывающий пусть замерит стены и решит, куда
                         поворачивать
      'done'           - выбран лимит клеток
      'timeout'        - не уложились в бюджет времени на клетку
      'paused'         - кнопка на ESP
      'lifted'         - робота сняли с поля (моторы уже заглушены)
      'link_lost'      - телеметрия с ESP пропала
      'odo_fault'      - энкодеры молчат или одометрия не растёт на ровном полу
      'obstacle_stall' - не взяли препятствие; НЕ авария, вызывающий делает
                         откат и повтор
      'ramp'           - проехали горку целиком и стоим в центре первой
                         клетки после неё; замер в _last_ramp, в карту его
                         заносит вызывающий через record_ramp()
      'ramp_stall'     - встали на горке; робот уже откатился обратно в
                         клетку, откуда выехал, дальше - как obstacle_stall
      'black'          - въехали на чёрную плитку
      'wall_close'     - лидар видит стену ближе FRONT_EMERGENCY_MM; при n=0 -
                         стена прямо перед текущей клеткой
      'front_obstacle' - впереди внезапно что-то близко (не на границе
                         клетки), остановились, не доехав до середины;
                         робот уже вернулся в центр исходной клетки
      'bumper_*'       - концевики
    """
    z0 = get_z_cnt()
    zero_odo()
    # Раньше - sleep(0.04) вслепую: пакет с одометрией ДО "Z" брался за базу,
    # и защита от скачка (только >=100см) пропускала лишнюю клетку.
    if not wait_odo_zeroed(z0):
        print("    [WARN] ESP не подтвердил 'Z' за 0.2с - база одометрии без гарантии")

    target_yaw = snap_target()

    last_l, last_r = get_odo()
    traveled_cm = 0.0
    head_off_f = 0.0
    last_steer = 0.0
    cell_cm = CELL_MM / 10.0
    boundary_cm = cell_cm                 # центр ближайшей клетки по одометрии
    lead_cm = DECIDE_LEAD_MM / 10.0
    fwd = 0.0
    last_progress_cm = 0.0
    last_progress_t = time.monotonic()
    last_status_t = 0.0

    # Состояние ассиста. assist_mode: None | 'kick' | 'ramp'.
    #   assist_t0        - начало ТЕКУЩЕЙ фазы
    #   assist_total_t0  - начало всей попытки (предохранитель RAMP_TOTAL_MAX_S)
    #   assist_kicks     - сколько импульсов подряд без продвижения
    #   assist_progress_* - одометрия и время последнего реального продвижения
    #   assist_extra_s   - на сколько продлён бюджет времени клетки
    assist_mode = None
    assist_t0 = assist_total_t0 = 0.0
    assist_kicks = 0
    assist_gap_until = 0.0
    push_tries = 0             # PUSH_THROUGH_SMALL: сколько раз уже дотолкивали
    assist_progress_cm = 0.0
    assist_progress_t = 0.0
    assist_extra_s = 0.0
    ramp_announced = False
    telem_seq = _telem_seq

    # Горка для карты (см. RAMP_MAP_DEG):
    #   None   - ровно, или обычное препятствие/ступенька
    #   'cand' - наклон >= RAMP_MAP_DEG, ждём RAMP_CONFIRM_CM хода на нём;
    #            тормозить у границы клетки уже нельзя - вдруг это горка
    #   'on'   - горка: едем без цели по одометрии, передний лидар не слушаем
    #   'exit' - снова ровно, цель - центр первой клетки после гребня
    global _last_ramp
    _last_ramp = None
    ramp_state = None
    ramp_sign = 0
    ramp_cand_cm = 0.0
    ramp_flat_cm = None
    ramp_saved = None
    ramp_log = []
    # Всплески наклона на ступеньках/лежачих - см. BUMP_EXTRA_MM.
    bump_on = False
    bump_extra_cm = 0.0
    pitch_f = None          # сглаженный pitch_delta, см. RAMP_PITCH_ALPHA

    cells = 0
    # Одна клетка - остановка у первой же границы известна заранее, решать
    # на ходу нечего. Тормозной профиль тогда действует с самого старта и сам
    # начинает тормозить, когда пора, - крейсерская больше не ограничена
    # тормозным путём внутри DECIDE_LEAD_MM (см. MOVE_MAX_CMS).
    one_cell = max_cells <= 1
    pending = not one_cell  # решение по ближайшей границе ещё не принято
    stopping = one_cell     # решили тормозить у этой границы
    reason = "done" if one_cell else "stop"
    v_max = MOVE_MAX_CMS if one_cell else MOVE_MAX_NONSTOP_CMS
    black_back_cm = 0.0     # сколько отъехать назад, если поймали чёрное

    # Скорость по одометрии (для ассиста): окно SPEED_WIN_S, см. v_meas.
    odo_hist = deque()
    v_meas = 0.0
    # Ограничение хода на наклоне, с плавным (BRAKE_DECEL_CMS2) изменением,
    # чтобы сам переход на него не был рывком.
    tilt_lim = v_max
    last_loop_t = time.monotonic()

    # Опора для оценки дистанции до передней стены между сканами лидара
    f_anchor = None        # мм, последнее показание лидара
    f_anchor_cm = 0.0      # одометрия в момент этого показания
    last_seq = _scan_cnt
    wall_forced = False    # цель уже перенесена к внезапно близкой стене
    forced_from_cm = 0.0   # центр клетки, из которой ехали, когда это случилось

    # Наблюдатель меток на ходу (victim_watch.py): только на ровном и с той
    # стороны, где лидар видит стену. vmark - метка, ради которой тормозим
    # ({"side", "pos_mm", "stop_cm"}); пока она есть, наблюдатель выключен.
    # watcher = None - в этой поездке наблюдателя нет (или он умер).
    watcher = (_watcher if cell is not None and hdg is not None and not expect_ramp
               else None)
    side_hold = watch_logic.SideHold()
    odo_t = watch_logic.OdoHistory()
    vmark = None

    print(f"    движение  курс={target_yaw:.0f}°")

    watch_armed = False
    t0 = time.monotonic()
    t_cell = time.monotonic()    # таймаут считаем на клетку, а не на весь прогон
    while True:
        if _lifted.is_set():
            return cells, "lifted"
        if get_esp_paused():
            # BTN_1 - перезапуск с чекпоинта, в том числе с горки: робота
            # всё равно переносят руками, недоезженная горка не записывается.
            return cells, "paused"
        if not telem_fresh():
            reason = "link_lost"
            print(f"\n    АВАРИЯ: нет телеметрии {telem_age():.2f}с — торможу")
            break
        # Бюджет времени клетки продлевается ровно на длительность ассиста:
        # подъём по горке законно занимает секунды, и раньше он упирался в
        # этот таймаут, а клетка при этом молча терялась (cells не рос).
        if time.monotonic() - t_cell > CELL_TIMEOUT_S + assist_extra_s:
            reason = "timeout"
            print("    ТАЙМАУТ!")
            break

        # Наклон нужен уже здесь: по нему решается, каким таймером мерить
        # залипание одометрии - штатным или «мы на препятствии».
        pitch_delta = get_pitch() - _pitch_level

        # ── Одометрия ─────────────────────────────────────────
        cl, cr = get_odo()
        dl, dr = cl - last_l, cr - last_r
        if abs(dl) < 100 and abs(dr) < 100:   # скачок = только что было 'Z'
            traveled_cm += (dl + dr) / 2.0
        last_l, last_r = cl, cr

        now_m = time.monotonic()
        _tick_ms["вкл" if watch_armed else "выкл"].add((now_m - last_loop_t) * 1000.0)
        loop_dt = min(0.05, now_m - last_loop_t)
        last_loop_t = now_m
        odo_hist.append((now_m, traveled_cm))
        odo_t.add(now_m, traveled_cm)
        while len(odo_hist) > 2 and now_m - odo_hist[1][0] >= SPEED_WIN_S:
            odo_hist.popleft()
        t_a, d_a = odo_hist[0]
        if now_m - t_a > 0.02:
            v_meas = (traveled_cm - d_a) / (now_m - t_a)

        # Без двух энкодеров нельзя гарантировать остановку через 300 мм.
        if not encoders_online():
            reason = "odo_fault"
            l_ok, r_ok = encoder_sides()
            # Печатаем, КАКАЯ сторона молчит, и сырую одометрию рядом: бит в
            # телеметрии и строка debug_task на ESP считаются из одного и того
            # же isnan(), так что разойтись они не могут - и если ESP при этом
            # показывает живые энкодеры, значит расходятся версии или момент
            # замера, а не сами данные.
            print(f"\n    АВАРИЯ: энкодер не отвечает "
                  f"(левый={'ok' if l_ok else 'НЕТ'}, "
                  f"правый={'ok' if r_ok else 'НЕТ'}, "
                  f"L={cl:.1f} R={cr:.1f}см) — торможу")
            break
        # Нос задран - робот сейчас берёт препятствие, и постоять полсекунды
        # на месте для этого нормально. Раньше здесь работал один общий
        # ODO_STALL_S=0.7, который кончался на 50мс позже единственного
        # импульса момента: «не взял бордюр» = [FATAL] на весь заезд.
        on_obstacle = pitch_delta >= OBSTACLE_REARM_DEG or assist_mode is not None
        stall_limit = ASSIST_STALL_S if on_obstacle else ODO_STALL_S
        if traveled_cm >= last_progress_cm + ODO_PROGRESS_CM:
            last_progress_cm = traveled_cm
            last_progress_t = time.monotonic()
        elif (PUSH_THROUGH_SMALL and on_obstacle and ramp_state != 'on'
              and fwd >= MOVE_MIN_CMS and time.monotonic() - last_progress_t > stall_limit
              and push_tries < PUSH_THROUGH_MAX):
            push_tries += 1
            assist_kicks = 0
            assist_gap_until = 0.0
            last_progress_t = time.monotonic()
            t_cell = max(t_cell, time.monotonic() - CELL_TIMEOUT_S / 2)   # бюджет клетки тоже
            print(f"\n    бугорок не взят с ходу (pitch={pitch_delta:+.1f}°) - "
                  f"толкаю ещё, без отката ({push_tries}/{PUSH_THROUGH_MAX})")
        elif fwd >= MOVE_MIN_CMS and time.monotonic() - last_progress_t > stall_limit:
            if ramp_state == 'on' or (ramp_state == 'cand' and not PUSH_THROUGH_SMALL):
                reason = "ramp_stall"
                print(f"\n    ГОРКА НЕ ВЗЯТА на {traveled_cm*10:.0f}мм "
                      f"(pitch={pitch_delta:+.1f}°) — скатываюсь обратно")
            elif on_obstacle or ramp_state == 'cand':
                reason = "obstacle_stall"
                print(f"\n    ПРЕПЯТСТВИЕ НЕ ВЗЯТО (pitch={pitch_delta:+.1f}°, "
                      f"{assist_kicks} импульс(ов)) — откат и повтор")
            else:
                reason = "odo_fault"
                print("\n    АВАРИЯ: одометрия не растёт — торможу")
            break

        # ── Бампер: концевики спереди ─────────────────────────
        if get_bumper():
            side = bumper_side()
            reason = {"left": "bumper_left", "right": "bumper_right"}.get(side, "bumper_both")
            print(f"\n    БАМПЕР ({side}) на {traveled_cm*10:.0f}мм")
            break

        # ── Чёрная плитка: заезжать нельзя ────────────────────
        # Реагируем на первое же показание, без подтверждения вторым: датчик
        # обновляется ~10Гц, и одно лишнее подтверждение стоит ещё ~5см хода
        # вглубь чёрного. Запас по порогу большой (C=100 против порога ~210),
        # так что ложные срабатывания маловероятны.
        if tile_color() == TILE_BLACK:
            reason = "black"
            # Центр клетки, С КОТОРОЙ заехали: boundary_cm всегда указывает на
            # ближайший центр впереди, предыдущий - на клетку назад.
            black_back_cm = traveled_cm - (boundary_cm - cell_cm)
            print(f"\n    ЧЁРНАЯ (C={get_rgbc()[3]}) на {traveled_cm*10:.0f}мм - "
                  f"откат {black_back_cm*10:.0f}мм")
            break

        # ── Горка или всплеск: что под колёсами ──────────────
        pitch_f = pitch_delta if pitch_f is None else \
            pitch_f + (pitch_delta - pitch_f) * RAMP_PITCH_ALPHA
        p_abs = abs(pitch_f)
        ramp_log.append((traveled_cm, pitch_f))
        if ramp_state is None:
            # Каждый всплеск на ступеньке/лежачем - это лишние тики энкодера,
            # цель клетки отодвигаем (см. BUMP_EXTRA_MM). Начало горки сюда
            # тоже попадает, но там цель всё равно пересчитается от гребня.
            if not bump_on and p_abs >= OBSTACLE_PITCH_DEG:
                bump_on = True
                add = min(BUMP_EXTRA_MM / 10.0, BUMP_EXTRA_MAX_MM / 10.0 - bump_extra_cm)
                if add > 0:
                    bump_extra_cm += add
                    boundary_cm += add
            elif bump_on and p_abs < OBSTACLE_REARM_DEG:
                bump_on = False
            if p_abs >= RAMP_MAP_DEG:
                ramp_state = 'cand'
                ramp_sign = 1 if pitch_f > 0 else -1
                ramp_cand_cm = traveled_cm
                # Цель клетки до горки - вернуть её, если "горка" окажется
                # короткой лестницей (RAMP_MIN_LEN_CM).
                ramp_saved = (boundary_cm, stopping, pending, reason)
        elif ramp_state == 'cand':
            if p_abs < RAMP_MAP_DEG - RAMP_MAP_HYST_DEG or pitch_f * ramp_sign < 0:
                print(f"\n    не горка: {pitch_f:+.1f}°, наклон держался "
                      f"{(traveled_cm - ramp_cand_cm)*10:.0f}мм")
                ramp_state = None
            elif traveled_cm - ramp_cand_cm >= RAMP_CONFIRM_CM:
                ramp_state = 'on'
                stopping = pending = False
                print(f"\n    ГОРКА {'ВВЕРХ' if ramp_sign > 0 else 'ВНИЗ'} "
                      f"({pitch_f:+.1f}°) - еду без остановок до гребня")
        elif ramp_state == 'on':
            if p_abs < RAMP_FLAT_DEG:
                if ramp_flat_cm is None:
                    ramp_flat_cm = traveled_cm
                elif traveled_cm - ramp_flat_cm >= RAMP_FLAT_CM:
                    info = _ramp_measure(ramp_log, ramp_sign)
                    f_anchor = None      # всё, что лидар видел на склоне, - мусор
                    if not expect_ramp and (info["len_cm"] < RAMP_MIN_LEN_CM
                            or abs(info["rise_cm"]) < RAMP_MIN_RISE_CM):
                        # Лестница внутри клетки. Цель - прежняя; если уже
                        # проскочили её, остановка сразу, доводка по стене.
                        print(f"    не горка: наклон {info['len_cm']*10:.0f}мм, "
                              f"высота {info['rise_cm']*10:+.0f}мм - "
                              f"лестница/препятствие")
                        boundary_cm, stopping, pending, reason = ramp_saved
                        ramp_state = None
                        ramp_flat_cm = None
                        ramp_log = []
                    else:
                        _last_ramp = info
                        # Центр первой клетки - полклетки за гребнем, но не
                        # ближе RAMP_EXIT_MIN_MM от момента, когда стало ровно.
                        boundary_cm = max(info["crest_cm"] + cell_cm * 0.5,
                                          ramp_flat_cm + RAMP_EXIT_MIN_MM / 10.0)
                        ramp_state = 'exit'
                        stopping, pending, reason = True, False, "ramp"
                        print(f"    съехали: до центра клетки "
                              f"{(boundary_cm - traveled_cm)*10:.0f}мм")
            else:
                ramp_flat_cm = None
        on_slope_now = ramp_state in ('cand', 'on')
        if on_slope_now:
            # Подъём законно длится дольше CELL_TIMEOUT_S - пока одометрия
            # растёт, бюджет клетки не тратится (залипание ловит stall выше).
            t_cell = max(t_cell, last_progress_t)

        # ── Дистанция до передней стены на частоте петли ──────
        # Лидар даёт ~10 Гц, на подходе это замер раз в пару сантиметров.
        # Между сканами продлеваем последнее показание по одометрии, иначе
        # стена "прыгает" и по ней нельзя тормозить.
        #
        # Раньше ЛЮБОЙ пустой скан (f_now=None) мгновенно стирал якорь -
        # один битый оборот лидара (например, из-за нагрузки CPU от YOLO
        # сразу после победы жертвы на предыдущей клетке) полностью ослеплял
        # эту защиту до следующего валидного скана, и робот ехал по чистой
        # одометрии до самой стены. Теперь пустой скан якорь НЕ трогает -
        # экстраполяция по одометрии продолжается со старой, но реальной
        # точки. Сбрасываем якорь только когда лидар явно говорит "далеко"
        # (валидное f_now >= FRONT_TRACK_MM) или когда экстраполяция от него
        # зашла дальше ANCHOR_STALE_CM - тогда старой точке верить рискованно.
        seq = _scan_cnt
        walls = get_walls()      # один снимок стен на весь тик
        f_now = walls["front"]
        if on_slope_now or p_abs >= RAMP_MAP_DEG:
            # Перед лидара на склоне - это пол или небо. Стоя у подножия, он
            # вообще видит саму горку как стену в ~40см (130мм/tg25..30° + 15см),
            # и без этого робот вставал бы "у стены" на первой плитке горки.
            f_now = None
            f_anchor = None
        if seq != last_seq:
            last_seq = seq
            if f_now is not None:
                if f_now < FRONT_TRACK_MM:
                    f_anchor, f_anchor_cm = f_now, traveled_cm
                else:
                    f_anchor = None
            elif f_anchor is not None and traveled_cm - f_anchor_cm > ANCHOR_STALE_CM:
                f_anchor = None
        f_est = None if f_anchor is None else \
            f_anchor - (traveled_cm - f_anchor_cm) * 10.0

        # ── Наблюдатель меток ─────────────────────────────────
        # Только на ровном (не горка, не всплеск, не ассист) и только к
        # стене. Заметил - тормозим тем же профилем к stop_point (ниже, см.
        # mark_first), а наблюдатель гасим сразу: камера вернётся к обычной
        # выдержке, пока робот ещё тормозит.
        if watcher is not None:
            if watcher.dead:
                watcher, watch_armed = None, False
            else:
                sides = side_hold.update(now_m, {
                    "right": wall_present(walls["right"], SIDE_THRESH),
                    "left": wall_present(walls["left"], SIDE_THRESH)})
                flat = watch_logic.watch_allowed(ramp_state, bump_on, assist_mode,
                                                 pitch_delta, OBSTACLE_REARM_DEG, wall_forced)
                watch_armed = watcher.arm(sides if flat and vmark is None else set())
                for b in watcher.poll():
                    m = _watch_decide(b, cell, hdg, odo_t, vmark is not None)
                    if m is not None:
                        # Тормозим К МЕТКЕ: встать с ней в центре кадра, тем
                        # же профилем. Не успеваем - как можно раньше и
                        # подъезд назад (см. watch_logic.brake_target_cm).
                        m["stop_cm"], late = watch_logic.brake_target_cm(
                            m["pos_mm"], traveled_cm, fwd, MARK_BRAKE_DECEL_CMS2, STOP_LEAD_S)
                        vmark = m
                        watch_armed = watcher.arm(set())
                        print(f"    метка на ходу: торможу {'(поздно) ' if late else 'к метке '}"
                              f"через {(m['stop_cm'] - traveled_cm) * 10:.0f}мм")

        # Не глушится и на склоне: при лидаре на 130мм пол носом вниз ближе
        # FRONT_EMERGENCY_MM - это уклон больше 40°, а стена вплотную - всегда
        # стена. Поэтому берём сырое показание, а не обнулённое выше.
        f_raw = walls["front"]
        if f_raw is not None and f_raw <= FRONT_EMERGENCY_MM:
            print(f"\n    СТЕНА ВПЛОТНУЮ: f={f_raw:.0f}мм  d={traveled_cm*10:.0f}мм")
            # Раньше причина оставалась "stop"/"done" и клетка не засчитывалась
            # никогда. Два случая:
            #  - почти не сдвинулись: стена прямо перед клеткой, где стоим, а
            #    карта считала её открытой - вызывающий записывает её в карту
            #    (иначе BFS раз за разом выбирал тот же путь и робот "застревал"
            #    стоя на месте, см. MAX_STALLS);
            #  - проехали больше полклетки: мы уже в следующей клетке, просто
            #    ближе к стене, чем надо - засчитываем, доводка отъедет назад.
            reason = "wall_close"
            if traveled_cm >= (boundary_cm - cell_cm) + cell_cm * 0.5:
                cells += 1
            break

        # ── Сколько ещё ехать ─────────────────────────────────
        # Есть стена - правда у неё: едем ДО НЕЁ, а не до отметки одометрии,
        # поэтому робот встаёт в центре клетки сразу, без доводки после
        # остановки. Но верим ей, только если она согласна с одометрией в
        # пределах доводки: разошлись сильнее - значит это стена не этой
        # клетки (видно через открытый проём), и правит одометрия.
        rem_odo = boundary_cm - traveled_cm
        rem = rem_odo
        at_wall = False
        if f_est is not None:
            rem_wall = (f_est - FRONT_CENTER_MM) / 10.0
            if abs(rem_wall - rem_odo) <= ALIGN_MAX_MM / 10.0:
                rem = rem_wall
                at_wall = True

        # ── Страховка: стена ближе, чем тормозной путь ────────
        # Решение "ехать дальше" не должно быть неотменяемым: стену могли
        # увидеть позже (она была за порогом видимости, или лидар моргнул).
        # Если до места остановки у стены осталось меньше, чем нужно на
        # торможение - тормозим немедленно, не дожидаясь следующей границы.
        # Действует и когда остановка запланирована с места (one_cell): тогда
        # это случай "стена ближе, чем цель, и с одометрией не согласна".
        if f_est is not None and not wall_forced:
            need_cm = fwd * fwd / (2.0 * BRAKE_DECEL_CMS2)
            to_stop_cm = (f_est - FRONT_CENTER_MM) / 10.0
            if to_stop_cm <= need_cm * 1.3 and (not stopping or to_stop_cm < rem - 1.0):
                wall_forced = True
                forced_from_cm = boundary_cm - cell_cm
                stopping, pending = True, False
                boundary_cm = traveled_cm + to_stop_cm
                rem = to_stop_cm
                at_wall = True
                print(f"\n    стена близко: {f_est:.0f}мм - торможу немедленно")

        # ── Решение по подходящей границе клетки ──────────────
        # Принимается один раз за клетку, ровно за DECIDE_LEAD_MM до её
        # центра - раньше нельзя (боковое окно замера ещё читает предыдущую
        # клетку), позже нельзя (не успеем затормозить).
        if pending and rem <= lead_cm:
            pending = False
            br = wall_present(walls["right"], SIDE_THRESH)

            # Переднюю стену сравниваем не с сырым показанием, а с тем, каким
            # оно станет В ЦЕНТРЕ клетки: решение принимается за DECIDE_LEAD_MM
            # до центра, и та же стена читается на эти 110мм дальше. Без
            # пересчёта стена, дающая в центре нормальные ~180мм, здесь читалась
            # как 290мм, не проходила порог 260 - и робот уезжал в клетку со
            # стеной, считая её открытой. Прижатый концевик тут авторитетнее
            # лидара: вплотную к стене лидар её уже не видит (она ближе
            # собственного габарита робота).
            f_ref = f_est if f_est is not None else walls["front"]
            f_center = None if f_ref is None else f_ref - rem * 10.0
            bf = wall_present(f_center, WALL_THRESH) or get_bumper()

            if cells + 1 >= max_cells:
                stopping, reason = True, "done"
            elif not br or bf:
                stopping, reason = True, "stop"
            else:
                # Прямая продолжается - не тормозим вообще, просто отодвигаем
                # цель на клетку вперёд и едем дальше на крейсерской.
                cells += 1
                boundary_cm += cell_cm
                rem += cell_cm
                pending = True
                t_cell = time.monotonic()
                sys.stdout.write(f"\r    клетка {cells} пройдена с ходу      \n")

            if stopping:
                brake_dist = fwd * fwd / (2.0 * BRAKE_DECEL_CMS2)
                print(f"    торможение с {fwd:.0f}см/с: путь {brake_dist*10:.0f}мм "
                      f"из {rem*10:.0f}мм в запасе")

        # Остаток с поправкой на запаздывание петли: одометрия отстаёт, и на
        # ходу робот уже дальше, чем показывает. Поправка пропорциональна
        # скорости, поэтому у самой цели она сама сходит на нет.
        rem_eff = rem - fwd * STOP_LEAD_S

        # Точка остановки у метки ближе цели - тормозим к ней. Иначе робот
        # штатно встанет в центре (или у стены), и метку читаем там же.
        mark_first = vmark is not None and vmark["stop_cm"] - traveled_cm < rem
        if mark_first:
            rem = vmark["stop_cm"] - traveled_cm
            rem_eff = rem - fwd * STOP_LEAD_S

        if (stopping or mark_first) and rem_eff <= 0.0 and ramp_state != 'cand':
            if vmark is not None and not (wall_forced
                                          and traveled_cm < forced_from_cm + cell_cm * 0.5):
                # Стоим у метки (или в центре, если он был ближе): читаем её
                # здесь, потом - та же поездка дальше, без Z и без новой цели.
                t_stop = time.monotonic()
                out = _mark_stop(vmark, cell, hdg, target_yaw, traveled_cm)
                vmark = None
                if out in ("lifted", "paused"):
                    return cells, out
                if out == "link_lost":
                    reason = out
                    break
                pause_s = time.monotonic() - t_stop
                # Таймер клетки и сторожа застревания - на длительность паузы,
                # иначе после неё сразу timeout/odo_fault.
                (t_cell, last_progress_t, assist_gap_until, assist_t0, assist_total_t0,
                 assist_progress_t) = watch_logic.shift_timers(
                    (t_cell, last_progress_t, assist_gap_until, assist_t0, assist_total_t0,
                     assist_progress_t), pause_s)
                # Подъезд и развороты уже в энкодерах - добираем их в путь сразу.
                cl, cr = get_odo()
                traveled_cm += ((cl - last_l) + (cr - last_r)) / 2.0
                last_l, last_r = cl, cr
                last_progress_cm = traveled_cm
                t0 = last_loop_t = time.monotonic()     # новый плавный разгон с места
                fwd = last_steer = 0.0
                odo_hist.clear()
                f_anchor = None                         # перед - заново со свежего оборота
                last_seq = _scan_cnt
                side_hold.reset()
                left_cm = boundary_cm - traveled_cm
                print(f"    продолжаю: пауза {pause_s:.1f}с, до центра {left_cm * 10:.0f}мм")
                if stopping and left_cm * 10.0 < ALIGN_TOL_MM:
                    # Уже в центре или подъезд увёл за него - остаток доводкой.
                    if abs(left_cm) > 0.2:
                        creep_mm(left_cm * 10.0, target_yaw)
                    cells += 1
                    break
                telem_seq = wait_telem(telem_seq)
                continue
            if wall_forced and traveled_cm < forced_from_cm + cell_cm * 0.5:
                # Встали перед тем, что внезапно оказалось близко, не доехав
                # и до середины пути: это не стена следующей клетки (она
                # была бы на границе, и по ней остановка шла бы штатно), а
                # препятствие - например, кирпич у входа в неё. Клетку НЕ
                # засчитываем: раньше она засчитывалась, и робот считал, что
                # стоит в следующей клетке, недоехав до неё 10-25см.
                reason = "front_obstacle"
                f_txt = "—" if f_est is None else f"{f_est:.0f}"
                print(f"\n    препятствие впереди: f={f_txt}мм, "
                      f"проехали {(traveled_cm - forced_from_cm)*10:.0f}мм")
                break
            cells += 1
            if at_wall:
                print(f"\n    у стены: f={f_est:.0f}мм")
            break

        # ── Профиль скорости ──────────────────────────────────
        # Разгон - по времени (RAMP_UP_S). Торможение включается только когда
        # решено остановиться, и начинается ровно с текущей скорости.
        ss = min(1.0, (time.monotonic() - t0) / RAMP_UP_S)
        ss = ss * ss * (3.0 - 2.0 * ss)         # smoothstep, без ступеньки
        ramp_up = v_max * ss                     # от 0, не от MOVE_MIN_CMS -
                                                  # иначе на t=0 снова ступенька

        # Наклон: нос задран (заезд) или опущен (съезд) - ход ограничен, в том
        # числе и после импульса момента, иначе на гребне режим скорости сам
        # разгонял бы робота обратно до крейсерской прямо на спуск.
        if pitch_delta <= -OBSTACLE_PITCH_DEG:
            tilt_target = DESCENT_CAP_CMS
        elif pitch_delta >= OBSTACLE_PITCH_DEG or assist_mode is not None:
            tilt_target = TILT_CAP_CMS
        else:
            tilt_target = v_max
        tilt_step = BRAKE_DECEL_CMS2 * loop_dt
        tilt_lim = max(tilt_lim - tilt_step, min(tilt_lim + tilt_step, tilt_target))
        ramp_up = min(ramp_up, tilt_lim)

        braking = False
        if (stopping or mark_first) and ramp_state != 'cand':
            # Постоянное замедление: пока запас пути велик, sqrt даёт больше
            # крейсерской и ничего не ограничивает - робот едет полным ходом.
            # Тормозить начинает сам, ровно когда пути остаётся в обрез.
            decel = MARK_BRAKE_DECEL_CMS2 if mark_first else BRAKE_DECEL_CMS2
            v_brake = math.sqrt(2.0 * decel * max(0.0, rem_eff))
            braking = v_brake < ramp_up
            fwd = min(ramp_up, v_brake)
            if braking:
                fwd = max(fwd, MOVE_MIN_CMS * 0.5)   # чтобы не заглохнуть у самой цели
        else:
            fwd = ramp_up

        # ── Центровка: сдвигает цель курса, а не руль ─────────
        wl, wr = walls["left"], walls["right"]
        wall_l = wl is not None and wl < WALL_CENTER_MM
        wall_r = wr is not None and wr < WALL_CENTER_MM

        if wall_l and wall_r:
            wall_e = (wr - wl) * 0.5        # >0: прижались к левой стене
        elif wall_l:
            wall_e = SIDE_CENTER_MM - wl
        elif wall_r:
            wall_e = wr - SIDE_CENTER_MM
        else:
            wall_e = 0.0
        if abs(wall_e) < WALL_DEADBAND_MM:
            wall_e = 0.0

        yaw, yaw_rate = get_yaw_and_rate()   # один снимок на тик
        axis_e = angle_err(yaw, target_yaw)
        on_ramp = abs(pitch_delta) >= RAMP_PITCH_DEG
        wall_kp = RAMP_WALL_KP_DEG if on_ramp else WALL_KP_DEG
        wall_max = RAMP_WALL_MAX_DEG if on_ramp else WALL_MAX_DEG
        # На длинной горке гироскоп не накапливает поперечную ошибку: боковые
        # стены по лидару непрерывно сдвигают целевой курс к центру.
        head_off = max(-wall_max, min(wall_max, wall_e * wall_kp))
        head_off_f += (head_off - head_off_f) * HEAD_OFF_SMOOTH
        heading = (target_yaw + head_off_f) % 360

        # ── Руль: один быстрый контур по гироскопу ────────────
        # P по ошибке курса, D по ИЗМЕРЕННОЙ угловой скорости (не по разности
        # углов) - см. GYRO_KD_RATE. Фильтр производной больше не нужен:
        # фильтровать было нечего, кроме шума собственного дифференцирования.
        yaw_e = angle_err(yaw, heading)
        steer = -(yaw_e * GYRO_KP + yaw_rate * GYRO_KD_RATE)
        steer = max(-MAX_STEER_CMS, min(MAX_STEER_CMS, steer))
        # Та же кривая, что и у fwd: без этого при fwd≈0 и заметной ошибке
        # курса (например, сразу после поворота) команда получалась вида
        # (+20,-20) - робот резко крутился на месте вместо старта с места.
        steer *= ss
        # Ограничение рывка: срезает только скачки команды, в норме не влияет.
        d_max = STEER_SLEW_CMS_S * 0.010
        steer = max(last_steer - d_max, min(last_steer + d_max, steer))
        last_steer = steer

        # Ход сбрасываем по отклонению от ОСИ клетки, а не от смещённой
        # цели - иначе робот тормозил бы просто потому, что центруется.
        fwd *= max(0.35, 1.0 - abs(axis_e) / 18.0)

        # ── Ассист моментом: препятствие и горка ──────────────
        # Автомат состояний вместо прежней «одна попытка на событие»:
        #   горизонт  -> всё сбрасывается, попытки взводятся заново;
        #   pitch>=3° -> короткий сильный импульс ('kick'), и так до
        #                OBSTACLE_KICKS_MAX раз, причём счётчик обнуляет
        #                любое реальное продвижение;
        #   pitch>=10° дольше RAMP_CONFIRM_S -> это горка ('ramp'): ток ниже,
        #                держится не по общему времени, а пока одометрия
        #                растёт (RAMP_STALL_S).
        # Во время торможения у границы клетки момент не подаём (ток - это не
        # скорость, тормозной профиль им не отработать), но событие не
        # закрываем: перевзвод по-прежнему только по возврату в горизонт.
        # "Торможение" - это именно фаза спада скорости (braking), а не
        # "остановка запланирована": в one_cell она запланирована с места.
        #
        # Импульс - только если режим скорости не справляется (v_meas заметно
        # ниже заданного, см. OBSTACLE_SLOW_FRAC), и снимается сразу, как
        # робот разогнался выше потолка: значит, препятствие уже позади.
        pitch_up = pitch_delta

        if pitch_up < OBSTACLE_REARM_DEG:
            assist_mode = None
            assist_kicks = 0
            assist_gap_until = 0.0
            ramp_announced = False
        elif braking:
            assist_mode = None
        else:
            if assist_mode is not None:
                cap = RAMP_CAP_CMS if assist_mode == 'ramp' else OBSTACLE_CAP_CMS
                if v_meas > cap * 1.15:
                    print(f"\n    ассист снят: {v_meas:.0f}см/с > потолка {cap:.0f} - "
                          f"препятствие позади")
                    assist_mode = None
                    assist_kicks = 0
                    assist_gap_until = now_m + OBSTACLE_KICK_GAP_S
                    ramp_announced = False

            if (assist_mode is None and pitch_up >= OBSTACLE_PITCH_DEG
                    and v_meas < fwd * OBSTACLE_SLOW_FRAC
                    and now_m >= assist_gap_until
                    and assist_kicks < OBSTACLE_KICKS_MAX):
                assist_mode = 'kick'
                assist_kicks += 1
                assist_t0 = now_m
                if assist_kicks == 1:
                    assist_total_t0 = now_m
                assist_progress_cm, assist_progress_t = traveled_cm, now_m
                print(f"\n    препятствие #{assist_kicks}: pitch={pitch_up:+.1f}°, "
                      f"v={v_meas:.0f}/{fwd:.0f}см/с, момент {OBSTACLE_TORQUE_A:.1f}A "
                      f"(потолок {OBSTACLE_CAP_CMS:.0f}см/с)")

            if assist_mode == 'kick':
                if (pitch_up >= RAMP_PITCH_DEG
                        and now_m - assist_t0 >= RAMP_CONFIRM_S):
                    assist_mode = 'ramp'
                    assist_t0 = now_m
                    assist_progress_cm, assist_progress_t = traveled_cm, now_m
                elif now_m - assist_t0 > OBSTACLE_TORQUE_MAX_S:
                    assist_mode = None
                    assist_gap_until = now_m + OBSTACLE_KICK_GAP_S
                    if traveled_cm - assist_progress_cm >= OBSTACLE_PROGRESS_CM:
                        assist_kicks = 0     # сдвинулись - лимит попыток сбрасываем

            elif assist_mode == 'ramp':
                if traveled_cm >= assist_progress_cm + ODO_PROGRESS_CM:
                    assist_progress_cm, assist_progress_t = traveled_cm, now_m
                    assist_kicks = 0
                if (now_m - assist_progress_t > RAMP_STALL_S
                        or now_m - assist_total_t0 > RAMP_TOTAL_MAX_S):
                    # Встали на подъёме: момент снимаем, но следующий 'kick'
                    # (он сильнее) сам попробует сдвинуть робота.
                    assist_mode = None
                    assist_gap_until = now_m + OBSTACLE_KICK_GAP_S
                    ramp_announced = False
                    print("\n    горка: прогресса нет - снимаю момент")

        if assist_mode is not None:
            assist_extra_s = max(assist_extra_s, now_m - assist_total_t0)

        if assist_mode == 'ramp':
            if not ramp_announced:
                print(f"\n    горка: pitch={pitch_up:+.1f}°, "
                      f"момент {RAMP_TORQUE_A:.1f}A + коррекция курса")
                ramp_announced = True
            # steer уже ограничен ±MAX_STEER_CMS, так что отношение лежит
            # в ±1 и внешний clamp здесь - только страховка от правок выше.
            turn_a = max(-RAMP_STEER_A, min(RAMP_STEER_A,
                         (steer * TURN_SIGN / MAX_STEER_CMS) * RAMP_STEER_A))
            torque(RAMP_TORQUE_A + turn_a, RAMP_TORQUE_A - turn_a, RAMP_CAP_CMS)
        elif assist_mode == 'kick':
            turn_a = max(-OBSTACLE_STEER_A, min(OBSTACLE_STEER_A,
                         (steer * TURN_SIGN / MAX_STEER_CMS) * OBSTACLE_STEER_A))
            torque(OBSTACLE_TORQUE_A + turn_a, OBSTACLE_TORQUE_A - turn_a, OBSTACLE_CAP_CMS)
        else:
            motors(fwd + steer * TURN_SIGN, fwd - steer * TURN_SIGN)

        # Статус ≤10 Гц: на 200 Гц забитый pipe SSH тормозил бы сам цикл.
        if time.monotonic() - last_status_t >= STATUS_PERIOD_S:
            last_status_t = time.monotonic()
            sys.stdout.write(f"\r    кл.{cells + 1} ост.{rem*10:4.0f}мм  "
                             f"yaw={yaw:.1f}°(e={axis_e:+.1f})  "
                             f"we={wall_e:+.0f}→{head_off:+.1f}°  spd={fwd:.0f}   ")
            sys.stdout.flush()
        # Такт по приходу пакета, а не sleep(0.010): два независимых периода
        # по 10мс давали биение до целого периода сверху - самый дешёвый
        # источник запаздывания в контуре (см. STOP_LEAD_S). Таймаут только
        # страхует от зависания петли при обрыве линка.
        telem_seq = wait_telem(telem_seq)

    if watcher is not None:
        watcher.arm(set())      # доводке и скану стоя камера нужна в обычном режиме

    # Гребень уже позади - что бы ни остановило робота дальше (стена
    # вплотную, бампер, таймаут), он на другом этаже, и вызывающий обязан
    # занести горку в карту, а не шагнуть на соседа по одометрии.
    if ramp_state == 'exit' and reason not in ("lifted", "link_lost", "odo_fault"):
        cells, reason = 1, "ramp"

    # Никакого доката: профиль уже привёл скорость почти к нулю, поэтому сразу
    # в фиксацию. ESP держит 0 dps активно и повторяет команду, пока мы меряем
    # стены - так же жёстко, как в конце поворота.
    #
    # Исключение - робот в руках: _lift_thread уже заглушил моторы командой
    # stop(), и фиксировать 0 dps на весу значит драться с человеком.
    if _lifted.is_set():
        stop()
    else:
        settle_brake(0.06)

    if reason == "ramp_stall":
        # Скатываемся задом ровно на пройденное - обратно в центр клетки, из
        # которой выехали. Карта при этом не меняется: робот там же, где был.
        if traveled_cm > 0.2:
            creep_mm(-traveled_cm * 10.0, target_yaw,
                     timeout_s=2.0 + 1.5 * traveled_cm / ALIGN_SPEED_CMS)
    elif reason == "front_obstacle":
        # Назад в центр клетки, из которой выехали: по передней "стене" тут
        # не выровняться - это препятствие, а не граница клетки.
        back_cm = traveled_cm - forced_from_cm
        if back_cm > 0.2:
            creep_mm(-back_cm * 10.0, target_yaw,
                     timeout_s=2.0 + 1.5 * back_cm / ALIGN_SPEED_CMS)
    elif reason in ("lifted", "link_lost", "obstacle_stall"):
        # Выравниваться нечем и незачем: робота либо держат в руках, либо
        # связи нет, либо он упёрся в препятствие и решение принимает
        # вызывающий (flood_fill_run/return_to_start: откат и повтор).
        pass
    elif reason == "black":
        # Сдаём назад на ту клетку, с которой заехали. Доводку по стене здесь
        # не делаем: она встала бы по передней стене, то есть потащила бы
        # робота обратно к чёрному.
        if black_back_cm > 0.2:
            creep_mm(-black_back_cm * 10.0, target_yaw)
    else:
        # Проверяем СВЕЖИМ замером всегда. Раньше остановка "по стене" считалась
        # заведомо точной и доводка пропускалась - но дистанция там берётся из
        # f_est, продлённой одометрией между сканами лидара. Если та оценка
        # врала, ошибка ничем не ловилась, и следующий проезд начинался ближе к
        # стене, чем робот думал - ровно так он и попал бампером в стену.
        align_at_wall(target_yaw)
    print()
    return cells, reason


def creep_mm(dist_mm, target_yaw, timeout_s=2.0):
    """Проехать ровно dist_mm (знак = направление), держа курс по гироскопу.

    Меряем лидаром, а ЕДЕМ по одометрии: лидар обновляется 10 Гц, по нему
    15мм не отработать - прежняя доводка отмеряла ход секундомером и поэтому
    промахивалась. Разворот руля здесь работает одинаково вперёд и назад:
    вращение задаёт разность колёс, а не их знак.
    """
    l0, r0 = get_odo()
    v = math.copysign(ALIGN_SPEED_CMS, dist_mm)
    goal_cm = abs(dist_mm) / 10.0

    t0 = time.time()
    telem_seq = _telem_seq
    while time.time() - t0 < timeout_s:
        # Бампер останавливает только движение вперёд: отъезд назад от стены -
        # это как раз тот случай, когда концевик заведомо прижат.
        if interrupted() or (dist_mm > 0 and get_bumper()):
            break
        cl, cr = get_odo()
        # Та же поправка на запаздывание, что и в основном профиле: одометрия
        # показывает, где робот был ~30мс назад, поэтому цель считается
        # достигнутой чуть раньше. Без этого доводка регулярно проскакивала и
        # следующая итерация отыгрывала назад.
        if abs(((cl - l0) + (cr - r0)) * 0.5) >= goal_cm - abs(v) * STOP_LEAD_S:
            break
        yaw_e = angle_err(get_yaw(), target_yaw)
        st = -(yaw_e * GYRO_KP + get_yaw_rate() * GYRO_KD_RATE)
        st = max(-8.0, min(8.0, st))
        motors(v + st * TURN_SIGN, v - st * TURN_SIGN)
        telem_seq = wait_telem(telem_seq)

    brake()
    time.sleep(0.08)


@_timed("доводка")
def align_at_wall(target_yaw):
    """Доводка вдоль движения: встать в центр клетки по передней стене, а
    если её нет (например, после разворота) - по задней."""
    on_slope = abs(get_pitch() - _pitch_level) > SLOPE_BACK_GUARD_DEG
    for it in range(ALIGN_TRIES):
        if interrupted():
            return
        # Было measure_walls(2) - медиана из 2 это фактически БОЛЬШЕЕ из двух
        # значений (_median берёт sorted[len//2]), а не устойчивая середина.
        # На шумном замере это гоняло доводку туда-обратно (F=116 -> назад
        # 29мм -> следующий замер F=165 -> снова вперёд 20мм). WALL_VOTE_SCANS
        # (3) даёт настоящую медиану и заметно спокойнее.
        w = measure_walls(WALL_VOTE_SCANS)
        f, b = w["front"], w["back"]

        if f is not None and f < WALL_THRESH:
            need = f - FRONT_CENTER_MM          # >0: не доехали до центра
            src = f"F={f:.0f}"
        elif b is not None and b < BACK_THRESH and not on_slope:
            need = BACK_CENTER_MM - b           # >0: откатились назад
            src = f"B={b:.0f}"
        else:
            # На наклоне задняя ось - это пол, а не стена (SLOPE_BACK_GUARD_DEG),
            # и вставать по ней значит вставать по полу.
            if on_slope and b is not None and b < BACK_THRESH:
                print(f"    [выр] B={b:.0f}мм на наклоне - игнорирую")
            return                               # не по чему выравниваться

        if abs(need) < ALIGN_TOL_MM:
            if it:
                print(f"    [выр] ок, {src}мм")
            return
        if abs(need) > ALIGN_MAX_MM:
            print(f"    [выр] {src}мм: {need:+.0f}мм - это не доводка, пропускаю")
            return

        print(f"    [выр {it+1}] {src}мм  "
              f"{'вперёд' if need > 0 else 'назад'} {abs(need):.0f}мм")
        creep_mm(need, target_yaw)


def _interrupt_reason():
    """Причина бросить поездку посреди остановки у метки - те же, что
    проверяет такт drive_cells."""
    if _lifted.is_set():
        return "lifted"
    if get_esp_paused():
        return "paused"
    if not telem_fresh():
        return "link_lost"
    return None


def _watch_decide(b, cell, hdg, odo_t, busy):
    """Рамка наблюдателя -> метка, ради которой тормозить ({"side", "pos_mm"}),
    или None. Каждое срабатывание - строка [W] с картинкой: по ним подбирают
    порог, лишняя остановка стоит ~2с."""
    x1, y1, x2, y2 = b.xyxy
    side_px = max(x2 - x1, y2 - y1)
    t_cm = odo_t.at(b.t_frame) or 0.0
    off = watch_logic.px_to_mm(watch_logic.mark_center_y(b.xyxy))
    pos = watch_logic.mark_pos_mm(t_cm * 10.0, off)
    key, along = watch_logic.world_along(cell, hdg, watch_logic.wall_of(hdg, b.side),
                                         pos, LEVEL_STRIDE)
    stop, why = watch_logic.decide_stop(b.conf, side_px, key, along, _marks, busy,
                                        CONF_FAST, MIN_BOX_PX)
    print(f"\n    [W] {b.side} {b.cls} {b.conf:.2f} {side_px:.0f}px  путь {t_cm * 10:.0f}мм  "
          f"метка {pos:+.0f}мм (стена {key} {along:.0f}мм) → {why}  {b.image or ''}")
    return {"side": b.side, "pos_mm": pos} if stop else None


def _reject_mark(cell, hdg, side, pos_mm):
    """Наблюдатель сработал, а стоя не подтвердилось - больше здесь не стоим."""
    key, along = watch_logic.world_along(cell, hdg, watch_logic.wall_of(hdg, side),
                                         pos_mm, LEVEL_STRIDE)
    _marks.add(key, along, "rejected")


@_timed("камеры")
def _mark_stop(m, cell, hdg, target_yaw, base_cm):
    """Остановка на метку, замеченную на ходу (см. drive_cells): найти её стоя,
    подъехать так, чтобы была целиком в кадре, прочитать read_wall() и
    приписать клетке. Робот уже затормозил профилем; одометрия не обнулялась,
    base_cm - пройдено от центра исходной клетки. Возвращает причину бросить
    поездку ('paused'/'lifted'/'link_lost') или None - ехать дальше."""
    side = m["side"]
    det = _victim_r if side == "right" else _victim_l
    l0, r0 = get_odo()

    def trav_mm():
        cl, cr = get_odo()
        return (base_cm + ((cl - l0) + (cr - r0)) / 2.0) * 10.0

    settle_brake(0.06)
    if _watcher is not None:
        _watcher.wait_idle()
    r = _interrupt_reason()
    if r or det is None:
        return r

    def look():
        try:
            return det.best_fast()
        except Exception as e:
            print(f"    [WARN] кадр стоя ({side}): {e}")
            return None

    # 1. Где метка сейчас. Обычно робот проехал её на тормозном пути и в
    # кадре её уже нет - тогда подъезд по координате, запомненной на ходу.
    found = look()
    est = m["pos_mm"] - watch_logic.mark_pos_mm(trav_mm(), 0.0)
    creep, src = watch_logic.creep_to_mark(None if found is None else found[2], est,
                                           ALIGN_TOL_MM)
    if creep is None:
        print(f"    метка: нужен подъезд {est:+.0f}мм ({src}) - не верю, отбраковываю")
        _reject_mark(cell, hdg, side, m["pos_mm"])
        return None
    # 2. Подъезд
    if creep:
        print(f"    метка: подъезд {creep:+.0f}мм по {src}")
        creep_mm(creep, target_yaw)
        r = _interrupt_reason()
        if r:
            return r
        if found is not None:
            again = look()
            if again is not None:
                before = abs(watch_logic.px_to_mm(sum(found[2]) / 2.0))
                after = abs(watch_logic.px_to_mm(sum(again[2]) / 2.0))
                if after > before:
                    print(f"    [WARN] после подъезда метка дальше от центра кадра "
                          f"({before:.0f} -> {after:.0f}мм) - знак оси камеры? "
                          f"(watch_logic.CAM_CALIB_Y_MM)")
    # 3. Чтение - та же логика, что стоя в центре, без дедупа по стене
    trav = trav_mm()
    tcell, wall_dir = watch_logic.attribute(cell, _next_cell(cell[0], cell[1], hdg),
                                            hdg, side, trav)
    try:
        result = det.read_wall(tcell[0], tcell[1], wall_dir)
    except Exception as e:
        print(f"    [WARN] чтение метки ({side}): {e}")
        result = None
    if result is None:
        print(f"    метка не подтвердилась - место отбраковано ({side}, {trav:.0f}мм)")
        _reject_mark(cell, hdg, side, m["pos_mm"])
        return _interrupt_reason()
    key, along = _mark_world(result, cell, hdg, wall_dir, trav)
    _marks.add(key, along, "read")
    _scanned_walls.add((tcell[0], tcell[1], wall_dir))
    det.scanned.add((tcell[0], tcell[1], wall_dir))
    _victim_log.append({**result, "side": side, "wall_dir": wall_dir, "on_move": True,
                        "ts": time.strftime("%H:%M:%S")})
    print(f"    метка на ходу: {result['label']} → клетка {tcell}, стена "
          f"{_DIR_NAME[wall_dir]} (проехали {trav:.0f}мм)")
    r = _interrupt_reason()
    if r:
        return r
    if result.get("blink"):
        return _report_on_move(result, side, wall_dir, hdg, target_yaw)
    return None


# Число комплектов на тип жертвы - см. шапку victim_detect.py и правила
# RoboCup 2026 Rescue Maze.
KITS_BY_TYPE = {"damaged": 2, "stable": 1, "unharmed": 0}


def _mark_world(result, cell, hdg, wall_dir, traveled_mm):
    """(ключ стены, мм вдоль неё) прочитанной метки - по её рамке на кадре;
    traveled_mm - сколько робот проехал от центра cell курсом hdg (стоя в
    центре - 0)."""
    y1, y2 = result["box_y"]
    pos = watch_logic.mark_pos_mm(traveled_mm, watch_logic.px_to_mm((y1 + y2) / 2.0))
    return watch_logic.world_along(cell, hdg, wall_dir, pos, LEVEL_STRIDE)


@_timed("камеры")
def scan_sides(cx, cy, hdg, walls_rel=None):
    """Проверяет ОБЕ боковые стены (лево и право по камерам) и, если стена
    есть, сканирует её YOLO на жертву - при находке буквенной метки сразу
    разворачивается и репортит (см. report_victim).

    walls_rel - словарь с уже готовыми 'right'/'left' (True=стена), если он
    уже посчитан вызывающим (не мерить лидар второй раз); иначе меряется
    здесь. Вызывать и после поворота на месте (камеры смотрят уже на другие
    стены той же клетки), и после проезда в новую клетку: стена, которую
    уже сканировала ЛЮБАЯ из камер (_scanned_walls), второй раз не
    сканируется - после разворота на 180° правая и левая просто меняются
    местами, и раньше каждая камера пересматривала стену соседки.

    Возвращает курс, на котором робот остался: после выдачи аптечек он
    стоит спиной к метке и обратно не поворачивается (см. report_victim) -
    вызывающий обязан взять этот курс себе.
    """
    if _victim_r is None and _victim_l is None:
        return hdg
    if get_esp_paused():
        return hdg
    sides = []
    for side, det in (("right", _victim_r), ("left", _victim_l)):
        wall_dir = (hdg + (1 if side == "right" else 3)) % 4
        if det is not None and (cx, cy, wall_dir) not in _scanned_walls:
            sides.append((side, det, wall_dir))
    if not sides:
        return hdg      # смотреть нечего - и лидар не ждём
    if walls_rel is None:
        known = _maze.get((cx, cy))
        if (cx, cy) in _visited and known is not None:
            # Клетка уже снята при приезде - стены берём из карты, а не
            # ждём ещё два оборота лидара после каждого поворота.
            walls_rel = {"right": known[(hdg + 1) % 4] is True,
                         "left": known[(hdg + 3) % 4] is True}
        else:
            w = measure_walls(2)
            walls_rel = {"right": wall_present(w["right"], SIDE_THRESH),
                         "left": wall_present(w["left"], SIDE_THRESH)}
    jobs = [j for j in sides if walls_rel.get(j[0])]
    for _, _, wall_dir in jobs:
        _scanned_walls.add((cx, cy, wall_dir))

    # Обе камеры - одновременно: у каждой свой детектор (своя модель, своя
    # камера), делить им нечего. Съёмка кадра - это ожидание камеры, а YOLO
    # (torch) отпускает GIL, так что два скана вместе идут почти за время
    # одного, а не за сумму. Репорт - уже по очереди, после обоих сканов:
    # оба кадра сняты с одного и того же места.
    results = {}

    def _scan(side, det, wall_dir):
        try:
            results[side] = det.scan(cx, cy, wall_dir)
        except Exception as e:   # сбой одной камеры не должен ронять заезд
            print(f"    [WARN] скан {side}: {e}")
            results[side] = None

    threads = [threading.Thread(target=_scan, args=j, daemon=True) for j in jobs[1:]]
    for t in threads:
        t.start()
    if jobs:
        _scan(*jobs[0])
    for t in threads:
        t.join()

    for side, det, wall_dir in jobs:
        result = results.get(side)
        if result is None:
            continue
        # Та же метка могла быть прочитана на ходу из соседней клетки (или
        # с другой стороны стыка) - второй раз не репортим.
        key, along = _mark_world(result, (cx, cy), hdg, wall_dir, 0.0)
        dup = _marks.near(key, along)
        if dup is not None and dup[2] == "read":
            print(f"    [W] {side}: {result['label']} в {along:.0f}мм - уже прочитана "
                  f"рядом ({dup[1]:.0f}мм), не репортю")
            continue
        _marks.add(key, along, "read")
        if get_esp_paused():
            # Усыпили посреди скана: находку в лог, но ни мигать, ни
            # разворачиваться - робот должен замереть сразу.
            _victim_log.append({**result, "side": side,
                                 "wall_dir": wall_dir, "ts": time.strftime("%H:%M:%S")})
            continue
        # В лог для веб-страницы (map_web.py) идёт КАЖДЫЙ непустой
        # результат, включая фейковые когнитивные цели. Разворот, индикация
        # и выдача аптечек - только для настоящих жертв (blink): буквы
        # Φ/Ψ/Ω и когнитивные цели с суммой колец 0/1/2.
        _victim_log.append({**result, "side": side,
                             "wall_dir": wall_dir, "ts": time.strftime("%H:%M:%S")})
        if result.get("blink"):
            hdg = report_victim(result, side, wall_dir, hdg)
    return hdg


def scan_cell(cx, cy, hdg, walls_rel=None):
    """scan_sides(), пока курс не перестанет меняться: развернувшись спиной
    к метке для выдачи, робот смотрит камерами на две другие стены той же
    клетки - их тоже надо проверить. Каждая стена сканируется один раз
    (_scanned_walls), поэтому цикл конечен. Возвращает итоговый курс."""
    h = scan_sides(cx, cy, hdg, walls_rel)
    while h != hdg and not get_esp_paused():
        hdg = h
        h = scan_sides(cx, cy, hdg)
    return h


def _blink_victim(result, side):
    """Индикация лентой (как требуют правила - 5+с неподвижно). Возвращает,
    сколько комплектов выдавать: сколько нужно, но не больше, чем осталось -
    нечего выдать, значит только индикация, она засчитывается и без них."""
    need = KITS_BY_TYPE.get(result["type"], 0)
    n_kits = min(need, kits_left())
    short = f" (нужно {need}, в запасе {kits_left()})" if n_kits < need else ""
    print(f"    ▓ {result['label']} ({result['type']}, {side}): индикация "
          f"{VICTIM_STOP_S + MARGIN_S:.1f}с, аптечек={n_kits}{short}")
    if _leds is not None:
        hold_while(blink_pink, _leds, stop=get_esp_paused)
    return n_kits


@_timed("жертва")
def report_victim(result, side, wall_dir, hdg):
    """Сначала мигает лентой (робот и так в пределах 15см от стены сбоку -
    SIDE_CENTER_MM=140мм, разворот для этого не нужен). Дальше - только если
    реально есть что высыпать: разворачивается спиной к стене с меткой (та
    стена, что была сбоку по ходу - справа или слева, см. side - после
    поворота на ∓90° оказывается сзади), встаёт к ней по правилам (см.
    BACK_CENTER_MM) и высыпает нужное число аптечек. Обратно НЕ
    поворачивается: раньше робот возвращался на исходный курс, а следующим
    шагом маршрута нередко снова поворачивал туда же - два лишних поворота
    на каждую жертву. Теперь маршрут строится от того курса, на котором
    робот остался. Для unharmed (0 аптечек) разворот и подъезд не нужны
    вовсе - только мигание. Вызывать сразу после scan(), пока робот ещё
    стоит в той же клетке.

    wall_dir - абсолютное направление стены с меткой, hdg - текущий курс.
    Возвращает курс после выдачи.
    """
    n_kits = _blink_victim(result, side)
    if get_esp_paused():
        return hdg

    if n_kits == 0:
        return hdg

    # Спиной к метке: курс, противоположный стене. Считаем от ТЕКУЩЕГО
    # курса, а не от стороны камеры - если в клетке две жертвы, после
    # выдачи первой робот уже развёрнут, и вторая может оказаться спереди.
    back_hdg = (wall_dir + 2) % 4
    delta = DIR_DELTA[(back_hdg - hdg) % 4]
    if delta != 0:
        ok = turn(delta)
        if get_esp_paused():
            return hdg
        if not ok and gyro_heading() != back_hdg:
            print("    не развернулся спиной к метке - комплекты не выдаю")
            return gyro_heading()
        hdg = back_hdg
        align_at_wall(snap_target())     # "зад" - к метке, по правилам

    for _ in range(n_kits):
        if get_esp_paused():
            return hdg
        dispense_kit()
    return hdg


@_timed("жертва")
def _report_on_move(result, side, wall_dir, hdg, target_yaw):
    """Жертва, найденная посреди клетки (см. _mark_stop): мигание; если есть
    что выдавать - спиной к стене, выдача и поворот ровно обратно на
    target_yaw, потому что поездка продолжается. align_at_wall не нужен:
    робот и так в ~14см от стены. Возвращает причину бросить поездку или None."""
    n_kits = _blink_victim(result, side)
    r = _interrupt_reason()
    if r or n_kits == 0:
        return r
    ok = turn(DIR_DELTA[((wall_dir + 2) % 4 - hdg) % 4])
    r = _interrupt_reason()
    if r:
        return r
    if ok:
        for _ in range(n_kits):
            r = _interrupt_reason()
            if r:
                return r
            dispense_kit()
    else:
        print("    не развернулся спиной к метке - комплекты не выдаю")
    for _ in range(2):
        if turn_to(target_yaw):
            return None
        r = _interrupt_reason()
        if r:
            return r
    print("    [WARN] не вернулся на курс - доведёт руль drive_cells")
    return None


DIR_DELTA = {0: 0, 1: 90, 2: 180, 3: -90}   # (d - hdg) % 4 -> градусы для turn()

# Сколько раз подряд asymметричный бампер в одном направлении пробуем
# объехать маневром, прежде чем сдаться и считать ребро стеной.
BUMPER_SIDE_RETRIES = 3
# Сколько итераций подряд без единого продвижения (по любой причине) прежде
# чем считать разведку зашедшей в тупик и прекращать заезд как FATAL.
MAX_STALLS = 5


def _measure_cell(hdg):
    """Один голосующий замер стоя -> {'front','right','left','back': bool}
    (True=стена). confirmed, а не обычный measure_walls(): сразу после
    YOLO-скана жертвы лидар мог отдать пустой перед просто из-за нагрузки
    на CPU, а верить "открыто" здесь - ехать в стену. Прижатый концевик
    авторитетнее лидара: стена вплотную ближе собственного габарита робота
    и из замера отфильтрована."""
    return _walls_rel_map(measure_front_confirmed())


def _walls_rel_map(w):
    """Замер стоя -> {'front','right','left','back': bool} по порогам карты
    (FRONT_MAP_WALL_MM / BACK_MAP_WALL_MM)."""
    return {
        "front": wall_present(w["front"], FRONT_MAP_WALL_MM) or get_bumper(),
        "right": wall_present(w["right"], SIDE_THRESH),
        "left":  wall_present(w["left"], SIDE_THRESH),
        "back":  wall_present(w["back"], BACK_MAP_WALL_MM),
    }


def _arrived_cell(cx, cy, hdg, reason):
    """Где робот оказался после drive_cells(), проехавшего одну клетку."""
    if reason == "ramp":
        return record_ramp(cx, cy, hdg, _last_ramp,
                           measure=lambda: _measure_cell(hdg))
    if (cx, cy, hdg) in _ramps:
        # По карте здесь горка, а drive_cells её не узнал (наклон не дотянул
        # до RAMP_MAP_DEG). Шагнуть на соседа по одометрии нельзя - его в
        # карте нет, это плитка горки. Верим карте и печатаем - если это
        # когда-нибудь всплывёт в логе, порог RAMP_MAP_DEG велик для поля.
        print("    [WARN] по карте здесь горка, а наклона не было - "
              "считаю, что проехали её")
    return _next_cell(cx, cy, hdg)


# ══════════════════════════════════════════════════════════════
#  Разведка: BFS / flood-fill
# ══════════════════════════════════════════════════════════════
def flood_fill_run(max_cells):
    """Разведка неизвестного лабиринта: на каждой клетке, где робот ещё не
    стоял, снимает все 4 стены одним замером (карта в _maze), затем BFS
    ищет кратчайший путь по известным открытым рёбрам до ближайшей ещё не
    посещённой клетки и едет туда. Останавливается сама, когда такой клетки
    не остаётся - возвращает (cx, cy, hdg, checkpoint, status), status:
    'explored' (лабиринт разведан), 'cap' (упёрлись в max_cells),
    'fatal' (связь/одометрия/полный затор - дальше ехать нельзя)."""
    cx, cy, hdg = 0, 0, 0
    checkpoint = (cx, cy, hdg)
    stalls = 0
    obstacle_fails = 0
    bumper_side_fails = 0
    total = 0

    def arrive(new_cell):
        """Стоим в центре (cx,cy). Если клетка новая - снимаем стены и
        сканируем обе боковые камеры; в любом случае проверяем плитку.
        Курс может измениться: после выдачи аптечек робот остаётся спиной
        к метке (см. report_victim)."""
        nonlocal checkpoint, hdg
        # Позицию - на веб сразу по приезде, не дожидаясь замера стен, синей
        # стоянки и камер: иначе робот на карте отставал на всё это время.
        _write_state(cx, cy, hdg, checkpoint, "exploring")
        # Стены мерим и на повторном проезде: каждый замер - лишний голос
        # (см. vote_wall), и ошибка первого приезда исправляется сама.
        walls_rel = _measure_cell(hdg)
        set_cell_walls(cx, cy, hdg, walls_rel)
        if new_cell:
            _visited.add((cx, cy))
        _write_state(cx, cy, hdg, checkpoint, "exploring")   # стены

        if get_esp_paused():
            return      # спим - ни синей стоянки, ни сканов; разберётся цикл
        tile = tile_color()
        # Живое распознавание ИЛИ клетка уже когда-то была признана синей -
        # см. blue_stop()/_blue_cells: однажды подтверждённому факту доверяем
        # больше, чем одному текущему замеру датчика цвета.
        if tile == TILE_BLUE or (cx, cy) in _blue_cells:
            blue_stop((cx, cy))
        # Чекпоинт запоминается стоя в центре клетки: на ходу цвет не
        # читается при задранном носе (PITCH_COLOR_GUARD_DEG).
        if tile == CHECKPOINT_TILE and checkpoint[:2] != (cx, cy):
            checkpoint = (cx, cy, hdg)
            print(f"  ✓ ЧЕКПОИНТ ({cx},{cy}) курс={_DIR_NAME[hdg]}")

        if new_cell:
            hdg = scan_cell(cx, cy, hdg, walls_rel)

        _write_state(cx, cy, hdg, checkpoint, "exploring")

    arrive(True)     # стартовая клетка
    t_step = t_snap = None   # хронометраж шага, см. time_report()

    while total < max_cells:
        # Подъём - раньше паузы: пока робот в руках, тормозить и мерить
        # стены бессмысленно.
        if _lifted.is_set():
            handle_lift(checkpoint[2])
            cx, cy, hdg = checkpoint
            print(f"  ↩ Продолжаем с чекпоинта ({cx},{cy}) курс={_DIR_NAME[hdg]}")
            _write_state(cx, cy, hdg, checkpoint, "exploring")
            stalls = obstacle_fails = bumper_side_fails = 0
            continue

        if get_esp_paused():
            _write_state(cx, cy, hdg, checkpoint, "sleep")
            cx, cy, hdg = restart_from_checkpoint(checkpoint)
            stalls = obstacle_fails = bumper_side_fails = 0
            _write_state(cx, cy, hdg, checkpoint, "exploring")
            continue

        if not telem_fresh():
            print(f"\n  [WARN] телеметрия молчит {telem_age():.1f}с - жду ESP...")
            t_wait = time.time()
            while not telem_fresh():
                if time.time() - t_wait > 5.0:
                    print("  [FATAL] Связь с ESP потеряна — заезд прекращён")
                    _write_state(cx, cy, hdg, checkpoint, "fatal")
                    return cx, cy, hdg, checkpoint, "fatal"
                time.sleep(0.05)
            continue

        path = find_frontier_path(cx, cy, hdg)
        if path is None:
            print("  ✓ Неразведанных клеток, достижимых по известной карте, "
                  "больше нет - разведка завершена")
            _write_state(cx, cy, hdg, checkpoint, "explored")
            return cx, cy, hdg, checkpoint, "explored"

        d = path[0]
        now = time.monotonic()
        if t_step is not None:
            print(time_report(t_snap, now - t_step))   # прошлый шаг целиком
        t_step, t_snap = now, dict(_tacc)
        print(f"─── ({cx},{cy}) {_DIR_NAME[hdg]} → {_DIR_NAME[d]}  {total}/{max_cells} ───")

        delta = DIR_DELTA[(d - hdg) % 4]
        if delta != 0:
            # Разворот на 180 - двумя поворотами по 90 со сканом между ними.
            # Камеры смотрят только вбок, и разворот одним махом оставлял
            # переднюю стену тупика (единственную, какую робот ещё не видел)
            # непросканированной: до разворота она спереди, после - сзади.
            # На середине она оказывается сбоку.
            steps = (90, 90) if abs(delta) == 180 else (delta,)
            replan = False
            for i, step in enumerate(steps):
                ok = turn(step)
                if get_esp_paused():
                    replan = True
                    break
                if not ok:
                    # Не доворачивал - курс в карте с гироскопа, маршрут заново.
                    hdg = gyro_heading()
                    _write_state(cx, cy, hdg, checkpoint, "exploring")
                    replan = True
                    break
                # После поворота стены поменялись местами - встаём в центр
                # клетки по тому, что видно. Мерить после поворота точнее, чем
                # предсказывать до него. Посередине разворота на 180° - не
                # надо: робот никуда не ехал, а через секунду ось опять
                # сменится, и доводка была чистым простоем.
                if i == len(steps) - 1:
                    align_at_wall(snap_target())
                hdg = (hdg + step // 90) % 4
                _write_state(cx, cy, hdg, checkpoint, "exploring")
                # Камеры смотрят теперь на другие стены той же клетки -
                # сканируем их, не дожидаясь проезда вперёд.
                h = scan_cell(cx, cy, hdg)
                if get_esp_paused():
                    replan = True
                    break
                if h != hdg:
                    # Выдали аптечку и остались спиной к метке - остаток
                    # поворота посчитан от старого курса, строим шаг заново.
                    hdg = h
                    _write_state(cx, cy, hdg, checkpoint, "exploring")
                    replan = True
                    break
            if replan:
                continue

        n, reason = drive_cells(1, expect_ramp=(cx, cy, hdg) in _ramps,
                                cell=(cx, cy), hdg=hdg)
        if n > 0:
            if reason != "ramp":
                open_edge(cx, cy, hdg)   # проехали - значит, проход (горку пишет record_ramp)
            cx, cy = _arrived_cell(cx, cy, hdg, reason)
            total += 1
            arrive((cx, cy) not in _visited)

        if reason in ("paused", "lifted", "link_lost"):
            stalls = 0
            continue      # разбирается в начале следующей итерации

        if reason == "odo_fault":
            print("  [FATAL] Нет надёжной одометрии — заезд прекращён")
            _write_state(cx, cy, hdg, checkpoint, "fatal")
            return cx, cy, hdg, checkpoint, "fatal"

        if reason in ("obstacle_stall", "ramp_stall"):
            # НЕ фатально: это «не взял препятствие», а не отказ одометрии.
            # Откатываемся, чтобы колёса сошли с бордюра и снова зацепились
            # за пол, и пробуем то же ребро заново - ассист в drive_cells
            # при этом взведётся с нуля (нос вернулся в горизонт на откате).
            # С горки drive_cells уже скатился в центр исходной клетки сам.
            obstacle_fails += 1
            if reason == "obstacle_stall":
                creep_mm(-OBSTACLE_BACKOFF_MM, snap_target())
            if obstacle_fails <= OBSTACLE_RETRIES:
                print(f"    препятствие не взято "
                      f"({obstacle_fails}/{OBSTACLE_RETRIES}) - откат и повтор")
                stalls = 0
                continue
            # Исчерпали попытки - считаем ребро непроезжим, BFS обойдёт его.
            print("    препятствие не взято - считаю ребро непроезжим")
            block_direction(cx, cy, hdg)
            obstacle_fails = 0
            stalls = 0
            continue
        obstacle_fails = 0

        if reason == "front_obstacle":
            # Кирпич или что-то ещё у входа в следующую клетку - проехать
            # прямо нельзя. Ребро закрыто только с этой стороны (а не вся
            # клетка, как у чёрной): в неё можно попасть с другой стороны.
            print("    препятствие у входа в клетку - ребро закрыто")
            close_edge(cx, cy, hdg)
            stalls = 0
            continue

        if reason == "wall_close" and n == 0:
            # Стена прямо перед нами, а карта считала проход открытым (например,
            # боковой замер соврал после переезда центра). Без записи в карту
            # BFS выбирал тот же путь снова и снова - робот "застревал" стоя.
            print("    стена вплотную перед клеткой - записываю её в карту")
            close_edge(cx, cy, hdg)
            stalls = 0
            continue

        if reason == "black":
            # Ребро в чёрную клетку непроезжее - BFS обойдёт его сам, без
            # жёстко зашитого разворота на 180.
            print("    чёрная клетка - ребро непроезжее")
            block_direction(cx, cy, hdg)
            stalls = 0
            continue

        if reason == "bumper_both":
            # Пока робот прижат к стене, лидар её не видит - следующий же
            # замер сказал бы "впереди свободно". Откат возвращает стену в
            # поле зрения, а карта сразу узнаёт про эту стену.
            print(f"    откат {BUMPER_BACKOFF_MM:.0f}мм - вплотную стену не видно")
            creep_mm(-BUMPER_BACKOFF_MM, snap_target())
            block_direction(cx, cy, hdg)
            stalls = 0
            continue

        elif reason in ("bumper_left", "bumper_right"):
            # Сработал только ОДИН концевик - задели что-то одним боком, не
            # стеной по центру. Объезд: поворот на 45° В СТОРОНУ ОТ задетого
            # бока, откат, возврат на исходный курс - и следующая итерация
            # сама попробует то же ребро заново. Знак подобран эмпирически
            # (как TURN_SIGN) - по факту "слева" оказалось направо.
            base_yaw = snap_target()
            away_deg = -45 if reason == "bumper_left" else 45
            side_ru = "слева" if reason == "bumper_left" else "справа"
            print(f"    асимметричный бампер ({side_ru}) - "
                  f"поворот {away_deg:+.0f}°, откат {BUMPER_SIDE_BACKOFF_MM:.0f}мм, возврат курса")
            turn(away_deg)
            if not get_esp_paused():
                creep_mm(-BUMPER_SIDE_BACKOFF_MM, get_yaw())
            if not get_esp_paused():
                turn_to(base_yaw)
            bumper_side_fails += 1
            if bumper_side_fails >= BUMPER_SIDE_RETRIES:
                print("    асимметричный бампер повторился - считаю ребро непроезжим")
                block_direction(cx, cy, hdg)
                bumper_side_fails = 0
            stalls = 0
            continue

        bumper_side_fails = 0
        # Защита от залипания: если робот несколько раз подряд не смог
        # продвинуться ни на клетку по ЛЮБОЙ причине, дальше крутиться
        # бессмысленно - что-то системно не так.
        stalls = stalls + 1 if n == 0 else 0
        if stalls >= MAX_STALLS:
            print("  [WARN] застряли - прекращаю разведку")
            _write_state(cx, cy, hdg, checkpoint, "fatal")
            return cx, cy, hdg, checkpoint, "fatal"

    print(f"  [WARN] потолок клеток ({max_cells}) исчерпан - прекращаю разведку")
    _write_state(cx, cy, hdg, checkpoint, "cap")
    return cx, cy, hdg, checkpoint, "cap"


# ══════════════════════════════════════════════════════════════
#  Возврат на старт (BFS по уже известной карте)
# ══════════════════════════════════════════════════════════════
def return_to_start(cx, cy, hdg, checkpoint):
    """Едет на (0,0) по уже разведанной карте - тот же BFS, что и в
    flood_fill_run, только цель фиксированная и новых клеток не открывает.
    Возвращает (cx, cy, hdg); если старт не оказался достижим по известной
    карте (не должно случиться при связном лабиринте), возвращает текущую
    позицию, не доехав."""
    if (cx, cy) == (0, 0):
        return cx, cy, hdg
    print("\n  ↩ Возврат на старт (BFS по известной карте)")

    while (cx, cy) != (0, 0):
        if _lifted.is_set():
            handle_lift(checkpoint[2])
            cx, cy, hdg = checkpoint
            _write_state(cx, cy, hdg, checkpoint, "returning")
            continue

        if get_esp_paused():
            _write_state(cx, cy, hdg, checkpoint, "sleep")
            cx, cy, hdg = restart_from_checkpoint(checkpoint)
            _write_state(cx, cy, hdg, checkpoint, "returning")
            continue

        if not telem_fresh():
            t_wait = time.time()
            while not telem_fresh():
                if time.time() - t_wait > 5.0:
                    print("  [FATAL] Связь с ESP потеряна во время возврата")
                    _write_state(cx, cy, hdg, checkpoint, "fatal")
                    return cx, cy, hdg
                time.sleep(0.05)
            continue

        path = find_path_bfs((cx, cy), lambda c: c == (0, 0), hdg)
        if path is None:
            print("  [FATAL] Старт недостижим по известной карте — возврат прерван")
            _write_state(cx, cy, hdg, checkpoint, "fatal")
            return cx, cy, hdg

        d = path[0]
        delta = DIR_DELTA[(d - hdg) % 4]
        if delta != 0:
            ok = turn(delta)
            if get_esp_paused():
                continue
            if not ok:
                hdg = gyro_heading()
                _write_state(cx, cy, hdg, checkpoint, "returning")
                continue
            align_at_wall(snap_target())
            hdg = d
            _write_state(cx, cy, hdg, checkpoint, "returning")

        n, reason = drive_cells(1, expect_ramp=(cx, cy, hdg) in _ramps,
                                cell=(cx, cy), hdg=hdg)
        if n > 0:
            if reason != "ramp":
                open_edge(cx, cy, hdg)
            cx, cy = _arrived_cell(cx, cy, hdg, reason)
            # Позицию - до синей стоянки (она 6с), а не после.
            _write_state(cx, cy, hdg, checkpoint, "returning")
            # Голос и на обратном пути: если карта ошиблась, BFS сразу
            # перестроит маршрут до старта.
            if not get_esp_paused():
                set_cell_walls(cx, cy, hdg, _measure_cell(hdg))
            # Синяя клетка требует стоянки на КАЖДОМ визите, включая обратный
            # путь - см. blue_stop()/_blue_cells.
            if tile_color() == TILE_BLUE or (cx, cy) in _blue_cells:
                blue_stop((cx, cy))

        if reason in ("paused", "lifted", "link_lost"):
            continue
        if reason == "odo_fault":
            print("  [FATAL] Нет надёжной одометрии во время возврата")
            _write_state(cx, cy, hdg, checkpoint, "fatal")
            return cx, cy, hdg

        # Карта уже известна, но реальность может разойтись с ней (стену
        # чуть подвинули, лидар ошибся при разведке) - те же реакции, что и
        # при разведке: считаем ребро непроезжим и просим BFS искать заново.
        if reason in ("obstacle_stall", "ramp_stall"):
            if reason == "obstacle_stall":
                creep_mm(-OBSTACLE_BACKOFF_MM, snap_target())
            block_direction(cx, cy, hdg)
            continue
        if reason == "black":
            block_direction(cx, cy, hdg)
            continue
        if reason == "front_obstacle":
            close_edge(cx, cy, hdg)          # см. то же место в flood_fill_run
            continue
        if reason == "wall_close" and n == 0:
            close_edge(cx, cy, hdg)          # см. то же место в flood_fill_run
            continue
        if reason == "bumper_both":
            creep_mm(-BUMPER_BACKOFF_MM, snap_target())
            block_direction(cx, cy, hdg)
            continue
        if reason in ("bumper_left", "bumper_right"):
            base_yaw = snap_target()
            away_deg = -45 if reason == "bumper_left" else 45
            turn(away_deg)
            if not get_esp_paused():
                creep_mm(-BUMPER_SIDE_BACKOFF_MM, get_yaw())
            if not get_esp_paused():
                turn_to(base_yaw)
            block_direction(cx, cy, hdg)
            continue

    print(f"  ✓ На старте ({cx},{cy}) курс={_DIR_NAME[hdg]}")
    _write_state(cx, cy, hdg, checkpoint, "at_start")
    return cx, cy, hdg


def blink_start_return():
    """Индикация возврата на старт - ТЕМ ЖЕ светодиодом/лентой, что и для
    жертв, но своим рисунком: ВКЛ 1с/ВЫКЛ 1с, не менее 10 секунд (см.
    leds.blink_return). Тормоз держим фоновым потоком всё это время - иначе
    на наклонном полу робота может увести с центра стартовой клетки
    (то же самое hold_while, что и при индикации жертвы)."""
    if _leds is None:
        print("  [WARN] лента недоступна — мигание при возврате пропущено")
        return
    print("  ● Мигание на старте (возврат распознан): 1с/1с, ≥10с")
    hold_while(blink_return, _leds)


MAP_WEB_PORT = 8001   # см. map_web.py


def _local_ip():
    """Лучшая догадка о собственном IP в локальной сети - только чтобы
    напечатать ссылку на карту. connect() на UDP-сокете ничего не
    отправляет в сеть (он лишь выбирает исходящий интерфейс по таблице
    маршрутизации), поэтому работает и без интернета - было бы это самое
    подключение к Wi-Fi/роутеру."""
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
            s.connect(("8.8.8.8", 80))
            return s.getsockname()[0]
    except OSError:
        return "<IP робота>"


def start_map_web():
    """Поднимает map_web.py ОТДЕЛЬНЫМ процессом, чтобы карта открывалась
    сама вместе с заездом - без второго терминала. Именно процесс (через
    subprocess), а не поток в этом же nav.py: у него свой интерпретатор и
    свой GIL, так что Flask-сервер никак не отнимает CPU у моторной петли,
    лидара и YOLO (см. шапку файла про GIL-конкуренцию). Если порт занят
    или что-то не так - падает в СВОЙ лог (map_web.log), а не в этот заезд.
    """
    script = os.path.join(os.path.dirname(os.path.abspath(__file__)), "map_web.py")
    log_path = os.path.expanduser("~/maze/map_web.log")
    try:
        log_f = open(log_path, "w")
        proc = subprocess.Popen([sys.executable, script],
                                 stdout=log_f, stderr=subprocess.STDOUT)
        log_f.close()   # у дочернего процесса уже своя копия дескриптора
    except OSError as e:
        print(f"  [WARN] карта не запущена: {e} (лог: {log_path})")
        return None
    print(f"  Карта: http://{_local_ip()}:{MAP_WEB_PORT}/  (лог: {log_path})")
    return proc


