#    полом, поэтому порог 0.32 стоит ровно посередине с запасом ±0.14.
#
# 2. ЧЁРНАЯ от БЕЛОЙ по долям НЕ отличается вовсе (.25/.34/.38 против
#    .24/.35/.42 - это один и тот же серый спектр разной светлоты), их
#    разделяет только яркость: C=100 против 603, то есть в 6 раз. Но
#    абсолютное C плывёт вместе с освещением зала, поэтому порог берётся не
#    числом, а долей от замера на стартовой (белой) клетке.
